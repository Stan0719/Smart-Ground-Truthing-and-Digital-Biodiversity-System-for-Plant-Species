// Compile the actual website SFC and global CSS; never maintain a second copy.
import { build } from '../../web/node_modules/vite/dist/node/index.js';
import vue from '../../web/node_modules/@vitejs/plugin-vue/dist/index.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const result = await build({
  configFile: false,
  root,
  plugins: [vue()],
  resolve: {
    alias: [
      { find: /.*\/data\/prototypeAuth$/, replacement: path.join(root, 'recovery/bridge.js') },
      { find: 'vue', replacement: path.resolve(root, '../web/node_modules/vue/dist/vue.esm-bundler.js') },
      { find: 'vue-router', replacement: path.resolve(root, '../web/node_modules/vue-router/dist/vue-router.esm-bundler.js') },
    ],
  },
  define: {
    'process.env.NODE_ENV': JSON.stringify('production'),
    'import.meta.env.VITE_EMAILJS_SERVICE_ID': 'window.__otpSettings.serviceId',
    'import.meta.env.VITE_EMAILJS_OTP_TEMPLATE_ID': 'window.__otpSettings.templateId',
    'import.meta.env.VITE_EMAILJS_PUBLIC_KEY': 'window.__otpSettings.publicKey',
    __VUE_OPTIONS_API__: 'true',
    __VUE_PROD_DEVTOOLS__: 'false',
    __VUE_PROD_HYDRATION_MISMATCH_DETAILS__: 'false',
  },
  build: {
    write: false,
    lib: { entry: path.join(root, 'recovery/main.js'), formats: ['es'], fileName: 'recovery' },
    target: 'es2022',
    minify: true,
    cssCodeSplit: false,
  },
});
const output = (Array.isArray(result) ? result[0] : result).output;
const js = output.find((item) => item.type === 'chunk').code;
const css = output.filter((item) => item.type === 'asset' && item.fileName.endsWith('.css')).map((item) => item.source).join('\n');
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><style>${css}</style></head><body><div id="app"></div><script>window.__otpSettings=__OTP_SETTINGS__;</script><script type="module">${js.replaceAll('</script', '<\\/script')}</script></body></html>`;
await mkdir(path.join(root, 'generated'), { recursive: true });
await writeFile(path.join(root, 'generated/recoveryHtml.js'), `// Generated by npm run build:recovery. Edit the website source instead.\nexport default ${JSON.stringify(html)};\n`);
