import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { testPool } from './test-postgres.mjs'
import { postgresDatabase } from './postgres.mjs'
import { migrateAuth } from './migrate.mjs'
import { createAdminNotificationProducer } from './admin-notifications.mjs'

test('Admin account event producer uses isolated Migration 013 storage and active Admin recipients', async (t) => {
  const pool = await testPool()
  const db = postgresDatabase(pool, 'plant_auth')
  t.after(() => pool.end())
  await migrateAuth(db)
  await pool.query(`CREATE SCHEMA plant_app;
    CREATE TABLE plant_app.plant_observation(id TEXT PRIMARY KEY);
    CREATE TABLE plant_app.species_request_submission(request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
    CREATE TABLE plant_app.record_change_submission(id TEXT PRIMARY KEY)`)
  await pool.query(readFileSync(new URL('../../plant-conservation-backend/migrations/013-staff-notification-foundation.sql', import.meta.url), 'utf8'))
  for (const [id, role, status, mustChange] of [
    ['admin-a', 'Administrator', 'Active', 0],
    ['admin-b', 'Administrator', 'Active', 0],
    ['admin-pending', 'Administrator', 'Active', 1],
    ['inactive-admin', 'Administrator', 'Inactive', 0],
    ['officer', 'Conservation Officer', 'Active', 0],
  ]) {
    await db.prepare(`INSERT INTO users(id,name,username,email,role,status,password_hash,must_change_password)
      VALUES(?,?,?,?,?,?,'fixture-hash',?)`).run(id, id, id, `${id}@example.invalid`, role, status, mustChange)
  }
  const producer = createAdminNotificationProducer({ auth: { db } })
  assert.equal(await producer.accountEvent({ sourceKey: 'admin-account:staff_created:fixture-1', action: 'staff_created', accountName: 'Example Officer', role: 'Conservation Officer' }), true)
  assert.equal(await producer.accountEvent({ sourceKey: 'admin-account:staff_created:fixture-1', action: 'staff_created', accountName: 'Example Officer', role: 'Conservation Officer' }), false)
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM plant_app.staff_notification_event')).rows[0].n, 1)
  const recipients = (await pool.query('SELECT recipient_subject FROM plant_app.staff_notification ORDER BY recipient_subject')).rows.map((row) => row.recipient_subject)
  assert.deepEqual(recipients, ['staff:admin-a', 'staff:admin-b'])
  const event = (await pool.query('SELECT event_type,audience_role,resource_kind,metadata FROM plant_app.staff_notification_event')).rows[0]
  assert.equal(event.event_type, 'account_administration')
  assert.equal(event.audience_role, 'Administrator')
  assert.equal(event.resource_kind, 'system')
  assert.equal(event.metadata.account_name, 'Example Officer')
  assert.equal(JSON.stringify(event.metadata).includes('password'), false)

  await db.prepare("UPDATE users SET status='Inactive' WHERE role='Administrator'").run()
  assert.equal(await producer.accountEvent({ sourceKey: 'admin-account:staff_created:no-admins', action: 'staff_created', accountName: 'No recipient' }), false)
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM plant_app.staff_notification_event')).rows[0].n, 1)
})
