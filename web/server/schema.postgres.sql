-- Run only in the private AUTH_PG_SCHEMA, never public or Supabase auth.
CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE TABLE IF NOT EXISTS users (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, username TEXT NOT NULL,
 email TEXT NOT NULL UNIQUE, role TEXT NOT NULL CHECK(role IN ('Administrator','Conservation Officer','Botanist')),
 status TEXT NOT NULL DEFAULT 'Active' CHECK(status IN ('Pending Activation','Active','Inactive','Suspended')),
 password_hash TEXT, must_change_password INTEGER NOT NULL DEFAULT 1 CHECK(must_change_password IN (0,1)),
 last_login TEXT, postgres_user_id INTEGER UNIQUE CHECK(postgres_user_id BETWEEN 1 AND 2147483647),
 CHECK ((status='Pending Activation' AND password_hash IS NULL) OR (status!='Pending Activation' AND password_hash IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username ON users(lower(username));
CREATE TABLE IF NOT EXISTS visitors (
 id TEXT PRIMARY KEY,name TEXT NOT NULL,email TEXT NOT NULL UNIQUE,
 role TEXT NOT NULL DEFAULT 'Visitor' CHECK(role='Visitor'),
 status TEXT NOT NULL DEFAULT 'Active' CHECK(status IN ('Active','Inactive','Suspended')),
 password_hash TEXT NOT NULL,must_change_password INTEGER NOT NULL DEFAULT 0 CHECK(must_change_password IN (0,1)),last_login TEXT
);
CREATE TABLE IF NOT EXISTS sessions(token_hash TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),expires_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);
CREATE TABLE IF NOT EXISTS visitor_sessions(token_hash TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES visitors(id),expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS auth_events(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,created_at BIGINT NOT NULL,user_id TEXT,ip TEXT,reason TEXT NOT NULL,actor_id TEXT);
CREATE INDEX IF NOT EXISTS auth_events_ip_time ON auth_events(ip,created_at);
CREATE TABLE IF NOT EXISTS face_service_nonces(nonce TEXT PRIMARY KEY,expires_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS password_resets(id TEXT PRIMARY KEY,user_id TEXT,kind TEXT,code_hash TEXT,expires_at BIGINT NOT NULL,attempts INTEGER NOT NULL DEFAULT 0,used INTEGER NOT NULL DEFAULT 0 CHECK(used IN (0,1)));
CREATE TABLE IF NOT EXISTS activation_tokens(token_hash TEXT PRIMARY KEY,user_id TEXT NOT NULL REFERENCES users(id),expires_at BIGINT NOT NULL,used INTEGER NOT NULL DEFAULT 0 CHECK(used IN (0,1)));
CREATE TABLE IF NOT EXISTS security_settings(id INTEGER PRIMARY KEY CHECK(id=1),session_hours INTEGER NOT NULL DEFAULT 8 CHECK(session_hours BETWEEN 1 AND 24),login_limit INTEGER NOT NULL DEFAULT 30 CHECK(login_limit BETWEEN 5 AND 100));
INSERT INTO security_settings(id) VALUES(1) ON CONFLICT DO NOTHING;
-- One registry enforces uniqueness across both account tables, including races.
CREATE TABLE IF NOT EXISTS account_emails(email TEXT PRIMARY KEY,subject TEXT NOT NULL UNIQUE);
CREATE OR REPLACE FUNCTION maintain_account_email() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN DELETE FROM account_emails WHERE subject=OLD.id; RETURN OLD; END IF;
 IF TG_OP='UPDATE' THEN DELETE FROM account_emails WHERE subject=OLD.id; END IF;
 INSERT INTO account_emails(email,subject) VALUES(NEW.email,NEW.id);
 RETURN NEW;
END $$;
CREATE OR REPLACE FUNCTION restrict_account_sessions() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.status != 'Active' OR NEW.password_hash IS DISTINCT FROM OLD.password_hash OR NEW.role IS DISTINCT FROM OLD.role OR NEW.email IS DISTINCT FROM OLD.email THEN
  IF TG_TABLE_NAME='users' THEN DELETE FROM sessions WHERE user_id=NEW.id;
  ELSE DELETE FROM visitor_sessions WHERE user_id=NEW.id; END IF;
 END IF;
 IF NEW.email IS DISTINCT FROM OLD.email OR NEW.password_hash IS DISTINCT FROM OLD.password_hash OR NEW.status IS DISTINCT FROM OLD.status THEN
  UPDATE password_resets SET used=1 WHERE user_id=NEW.id;
 END IF;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS account_email ON users;
CREATE TRIGGER account_email AFTER INSERT OR UPDATE OF email OR DELETE ON users FOR EACH ROW EXECUTE FUNCTION maintain_account_email();
DROP TRIGGER IF EXISTS account_email ON visitors;
CREATE TRIGGER account_email AFTER INSERT OR UPDATE OF email OR DELETE ON visitors FOR EACH ROW EXECUTE FUNCTION maintain_account_email();
DROP TRIGGER IF EXISTS account_restrictions ON users;
CREATE TRIGGER account_restrictions AFTER UPDATE ON users FOR EACH ROW EXECUTE FUNCTION restrict_account_sessions();
DROP TRIGGER IF EXISTS account_restrictions ON visitors;
CREATE TRIGGER account_restrictions AFTER UPDATE ON visitors FOR EACH ROW EXECUTE FUNCTION restrict_account_sessions();
