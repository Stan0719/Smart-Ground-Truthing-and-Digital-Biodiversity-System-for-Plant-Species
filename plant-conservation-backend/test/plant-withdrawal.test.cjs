"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { readFileSync } = require("node:fs");
const { join } = require("node:path");
const { once } = require("node:events");
const { randomUUID } = require("node:crypto");
const { createPlantDatabase } = require("./postgres-fixture.cjs");
const { createPlantApp } = require("../server.js");

test("Original Plant withdrawal keeps audit, QR and linked records while closing Officer review", async (t) => {
  const pool = await createPlantDatabase();
  t.after(() => pool.end());
  await pool.query("SET search_path TO plant_app,pg_catalog");
  const migrate = async (name) => pool.query(readFileSync(join(__dirname, `../migrations/${name}.sql`), "utf8"));
  for (const name of ["004-species-requests", "006-atomic-plant-submissions", "008-record-change-submissions",
    "009-record-version-history", "021-observation-edit-requests", "022-cancel-edit-requests", "025-original-plant-withdrawal"])
    await migrate(name);
  await migrate("025-original-plant-withdrawal");
  await pool.query(`CREATE SCHEMA IF NOT EXISTS plant_app; CREATE TABLE plant_app.qr_code(qr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id INTEGER UNIQUE,qr_code TEXT UNIQUE NOT NULL,status TEXT NOT NULL)`);
  const species = (await pool.query("INSERT INTO species(scientific_name,common_name) VALUES('Species A','Common A') RETURNING species_id")).rows[0].species_id;
  await pool.query("INSERT INTO rbac_species_visibility(species_id,visibility) VALUES($1,'public')", [species]);
  let sequence = 0;
  async function plant(status, owner = "bot", observationStatus = status, speciesId = species) {
    const key = `withdraw-${++sequence}`;
    const row = (await pool.query(`INSERT INTO plant_record(species_id,registered_subject,scientific_name,rbac_status,qr_token)
      VALUES($1,$2,$3,$4,$5) RETURNING plant_id`, [speciesId, `staff:${owner}`, key, status, key])).rows[0];
    await pool.query("INSERT INTO plant_app.qr_code(plant_id,qr_code,status) VALUES($1,$2,'assigned')", [row.plant_id, key]);
    const observationId = randomUUID();
    await pool.query(`INSERT INTO plant_observation(id,plant_id,owner_subject,status,origin_type,content,client_key)
      VALUES($1,$2,$3,$4,'initial_registration',$5,$6)`,
    [observationId, row.plant_id, `staff:${owner}`, observationStatus,
      { heightCm: 20, healthStatus: "Healthy", lifeStage: "Mature", morphology: "Leaf" }, key]);
    return { id: row.plant_id, observationId, key };
  }
  const pending = await plant("Pending Review");
  await pool.query(`INSERT INTO record_version_history(id,record_type,plant_id,version_number,
    owner_subject,edited_by,status,snapshot) VALUES('pending-original-version','plant',$1,1,
    'staff:bot','staff:bot','Pending Review',$2)`, [pending.id, { observation_id: pending.observationId }]);
  const correction = await plant("Pending Review", "bot", "Correction Required");
  await pool.query(`INSERT INTO observation_review(id,observation_id,reviewer_subject,decision,comment)
    VALUES('correction-review',$1,'staff:officer','Correction Required','Improve details')`, [correction.observationId]);
  const approved = await plant("Approved", "bot", "Approved");
  const rejected = await plant("Pending Review", "bot", "Rejected");
  await pool.query(`INSERT INTO observation_review(id,observation_id,reviewer_subject,decision,comment)
    VALUES('rejection-review',$1,'staff:officer','Rejected','No match')`, [rejected.observationId]);
  const linked = await plant("Pending Review");
  await pool.query(`INSERT INTO plant_observation(id,plant_id,owner_subject,status,origin_type,content,client_key)
    VALUES('linked-observation',$1,'staff:bot','Draft','subsequent_observation','{}'::jsonb,'linked-key')`, [linked.id]);
  const proposedSpecies = (await pool.query(`INSERT INTO species(scientific_name,common_name,rbac_data)
    VALUES('Proposed Species','Proposed', '{"approvalStatus":"Pending Review","submittedBy":"staff:bot"}'::jsonb)
    RETURNING species_id`)).rows[0].species_id;
  const withSpeciesRequest = await plant("Pending Review", "bot", "Pending Review", proposedSpecies);
  await pool.query(`INSERT INTO species_request_submission(owner_subject,client_key,payload_hash,scientific_name,common_name,
    genus_name,family_name,conservation_status,description,habitat,photo,proposed_species_id)
    VALUES('staff:bot',$1,'hash','Proposed Species','Proposed','Genus','Family','Least Concern','Description','Forest',$2,$3)`,
    [withSpeciesRequest.key, Buffer.from([1]), proposedSpecies]);
  const roles = { bot: "Botanist", other: "Botanist", officer: "Conservation Officer" };
  const tokens = Object.fromEntries(Object.keys(roles).map((key, index) => [key, String(index + 1).repeat(64)]));
  const auth = { session: async (token) => {
    const account = Object.keys(tokens).find((key) => tokens[key] === token);
    return account ? { id: account, role: roles[account], status: "Active", mustChangePassword: false } : null;
  }, event: async () => {} };
  const server = createPlantApp({ pool, auth }).listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(async () => { server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); });
  async function call(path, user, body = {}) {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api${path}`, {
      method: "POST", headers: { "Content-Type": "application/json", Authorization: `Bearer ${tokens[user]}` }, body: JSON.stringify(body),
    });
    return { status: response.status, data: await response.json() };
  }
  async function read(path, user) {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api${path}`, {
      headers: { Authorization: `Bearer ${tokens[user]}` },
    });
    return { status: response.status, data: await response.json() };
  }
  const withdraw = (item, user = "bot") => call(`/plant-submissions/${item.id}/withdraw`, user);
  assert.equal((await read(`/plant-submissions/${pending.id}/withdrawal`, "bot")).data.eligible, true);
  assert.equal((await read(`/plant-submissions/${pending.id}/withdrawal`, "other")).status, 403);
  assert.equal((await withdraw(pending, "other")).status, 403);
  assert.equal((await withdraw(approved)).status, 409);
  assert.equal((await withdraw(rejected)).status, 409);
  assert.equal((await withdraw(linked)).status, 409);
  assert.equal((await withdraw(pending)).status, 200);
  assert.equal((await withdraw(correction)).status, 200);
  assert.equal((await withdraw(withSpeciesRequest)).status, 200);
  assert.equal((await withdraw(pending)).status, 409);
  assert.equal((await read(`/plant-submissions/${pending.id}/withdrawal`, "bot")).data.eligible, false);
  assert.equal((await call(`/observations/${pending.observationId}/review`, "officer",
    { decision: "Approved", comment: "Late", revision: 2 })).status, 409);
  const state = (await pool.query(`SELECT p.rbac_status,p.withdrawn_by,p.withdrawn_at,o.status AS observation_status,
    q.status AS qr_status,q.plant_id AS qr_plant_id FROM plant_record p
    JOIN plant_observation o ON o.plant_id=p.plant_id
    JOIN plant_app.qr_code q ON q.plant_id=p.plant_id WHERE p.plant_id=$1`, [pending.id])).rows[0];
  assert.equal(state.rbac_status, "Withdrawn");
  assert.equal(state.observation_status, "Withdrawn");
  assert.equal((await pool.query("SELECT status FROM record_version_history WHERE id='pending-original-version'")).rows[0].status, "Withdrawn");
  assert.equal(state.withdrawn_by, "staff:bot");
  assert.ok(state.withdrawn_at);
  assert.equal(state.qr_status, "assigned");
  assert.equal(String(state.qr_plant_id), String(pending.id));
  await migrate("025-original-plant-withdrawal");
  assert.equal((await pool.query("SELECT rbac_status FROM plant_record WHERE plant_id=$1", [pending.id])).rows[0].rbac_status, "Withdrawn");
  assert.equal((await pool.query("SELECT count(*)::integer AS count FROM business_audit WHERE action='plant_submission_withdrawn'")).rows[0].count, 3);
  assert.equal((await pool.query("SELECT count(*)::integer AS count FROM plant_observation WHERE id='linked-observation'")).rows[0].count, 1);
  assert.equal((await pool.query("SELECT request_status FROM species_request_submission WHERE proposed_species_id=$1", [proposedSpecies])).rows[0].request_status, "Pending Review");
  const activeQueue = await read("/observations?status=Pending%20Review", "officer");
  assert.equal(activeQueue.status, 200);
  assert.equal(activeQueue.data.observations.some((row) => row.id === pending.observationId || row.id === withSpeciesRequest.observationId), false);
  const withdrawnHistory = await read("/observations?status=Withdrawn", "officer");
  assert.equal(withdrawnHistory.status, 200);
  assert.ok(withdrawnHistory.data.observations.some((row) => row.id === pending.observationId));
  const history = await read(`/observations/${pending.observationId}`, "bot");
  assert.equal(history.data.observation.status, "Withdrawn");
  const racing = await plant("Pending Review");
  const outcomes = await Promise.all([
    withdraw(racing),
    call(`/observations/${racing.observationId}/review`, "officer", { decision: "Approved", comment: "Verified", revision: 1 }),
  ]);
  assert.deepEqual(outcomes.map((outcome) => outcome.status).sort(), [200, 409]);
  const final = (await pool.query("SELECT rbac_status FROM plant_record WHERE plant_id=$1", [racing.id])).rows[0].rbac_status;
  assert.ok(["Approved", "Withdrawn"].includes(final));
});
