async function createPlants(database, includeLegacy = true) {
  await database.query(`
    CREATE SCHEMA plant_app;
    CREATE TABLE plant_app.plant_record(
      plant_id INTEGER PRIMARY KEY,
      species_id INTEGER NOT NULL,
      qr_token TEXT NOT NULL,
      rbac_status TEXT NOT NULL DEFAULT 'Pending Review',
      registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    INSERT INTO plant_app.plant_record(plant_id, species_id, qr_token)
      VALUES (1, 7, 'assigned-token');
    ${includeLegacy ? `
      CREATE TABLE public.plant_record(
        plant_id INTEGER PRIMARY KEY,
        species_id INTEGER NOT NULL,
        qr_token TEXT NOT NULL,
        rbac_status TEXT NOT NULL DEFAULT 'Pending Review',
        registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
      INSERT INTO public.plant_record(plant_id, species_id, qr_token)
        VALUES (1, 7, 'assigned-token');
    ` : ""}
  `);
}

async function createQrTable(database, schema, parentSchema = schema) {
  await database.query(`
    CREATE TABLE ${schema}.qr_code(
      qr_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      plant_id INTEGER UNIQUE REFERENCES ${parentSchema}.plant_record(plant_id) ON DELETE SET NULL,
      qr_code TEXT NOT NULL UNIQUE,
      status TEXT NOT NULL DEFAULT 'generated',
      generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      assigned_at TIMESTAMPTZ,
      activated_at TIMESTAMPTZ,
      retired_at TIMESTAMPTZ
    );
    CREATE INDEX qr_code_status_idx ON ${schema}.qr_code(status);
  `);
}

async function runMigration(database) {
  await runSql(database, migration);
}

async function runInventoryMigration(database) {
  await runSql(database, inventoryMigration);
}

async function runSql(database, sql) {
  try {
    await database.query(sql);
  } catch (error) {
    await database.query("ROLLBACK");
    throw error;
  }
}

async function foreignKey(database, table, column) {
  return (await database.query(`
    SELECT referenced_namespace.nspname || '.' || referenced_table.relname AS parent,
      constraint_row.convalidated, constraint_row.confdeltype
    FROM pg_constraint constraint_row
    JOIN pg_class source_table ON source_table.oid = constraint_row.conrelid
    JOIN pg_namespace source_namespace ON source_namespace.oid = source_table.relnamespace
    JOIN pg_class referenced_table ON referenced_table.oid = constraint_row.confrelid
    JOIN pg_namespace referenced_namespace ON referenced_namespace.oid = referenced_table.relnamespace
    WHERE source_namespace.nspname = $1 AND source_table.relname = $2
      AND constraint_row.contype = 'f' AND constraint_row.conname = $3
  `, [table.split(".")[0], table.split(".")[1], column])).rows[0];
}

test("moving the legacy inventory preserves rows, indexes, identity, and incoming foreign keys", async (t) => {
  const database = await testPool();
  t.after(() => database.end());
  await createPlants(database);
  await createQrTable(database, "public", "public");
  await database.query(`
    INSERT INTO public.qr_code(plant_id, qr_code, status, assigned_at)
    VALUES (1, 'assigned-token', 'assigned', CURRENT_TIMESTAMP);
    CREATE TABLE public.qr_code_link(
      link_id INTEGER PRIMARY KEY,
      qr_id BIGINT NOT NULL REFERENCES public.qr_code(qr_id) ON DELETE CASCADE
    );
    INSERT INTO public.qr_code_link VALUES (1, 1);
  `);

  const before = (await database.query(
    "SELECT qr_id, plant_id, qr_code, status, assigned_at FROM public.qr_code",
  )).rows;
  await runMigration(database);

  assert.deepEqual((await database.query(
    "SELECT qr_id, plant_id, qr_code, status, assigned_at FROM plant_app.qr_code",
  )).rows, before);
  assert.equal((await database.query(
    "SELECT to_regclass('public.qr_code') IS NULL AS absent",
  )).rows[0].absent, true);
  assert.ok((await database.query(
    "SELECT 1 FROM pg_indexes WHERE schemaname='plant_app' AND indexname='qr_code_status_idx'",
  )).rows.length);
  assert.equal((await foreignKey(database, "plant_app.qr_code", "qr_code_plant_id_fkey")).parent,
    "plant_app.plant_record");
  assert.equal((await foreignKey(database, "public.qr_code_link", "qr_code_link_qr_id_fkey")).parent,
    "plant_app.qr_code");
  assert.equal((await database.query(`
    SELECT identity_schema.nspname
    FROM pg_class identity_sequence
    JOIN pg_namespace identity_schema
      ON identity_schema.oid = identity_sequence.relnamespace
    WHERE identity_sequence.oid =
      to_regclass(pg_get_serial_sequence('plant_app.qr_code', 'qr_id'))
  `)).rows[0].nspname, "plant_app");
  assert.equal((await database.query(
    "SELECT qr_id FROM plant_app.qr_code WHERE qr_code='assigned-token'",
  )).rows[0].qr_id, 1);
  assert.equal((await database.query(
    "INSERT INTO plant_app.qr_code(qr_code) VALUES('next-token') RETURNING qr_id",
  )).rows[0].qr_id, 2);
  await database.query("DELETE FROM plant_app.plant_record WHERE plant_id=1");
  assert.equal((await database.query(
    "SELECT plant_id FROM plant_app.qr_code WHERE qr_code='assigned-token'",
  )).rows[0].plant_id, null);
});

