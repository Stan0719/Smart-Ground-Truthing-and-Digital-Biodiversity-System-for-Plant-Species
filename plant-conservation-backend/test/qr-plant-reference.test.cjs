test("both inventory tables cause a safe conflict without changing either", async (t) => {
  const database = await testPool();
  t.after(() => database.end());
  await createPlants(database);
  await createQrTable(database, "public", "public");
  await createQrTable(database, "plant_app");
  await database.query(`
    INSERT INTO public.qr_code(qr_code) VALUES('legacy-token');
    INSERT INTO plant_app.qr_code(qr_code) VALUES('app-token');
  `);

  await assert.rejects(runMigration(database), /Both public\.qr_code and plant_app\.qr_code exist/);

  assert.equal((await database.query("SELECT qr_code FROM public.qr_code")).rows[0].qr_code,
    "legacy-token");
  assert.equal((await database.query("SELECT qr_code FROM plant_app.qr_code")).rows[0].qr_code,
    "app-token");
});

test("legacy FK repair remains usable before the move and does not disrupt it", async (t) => {
  const database = await testPool();
  t.after(() => database.end());
  await createPlants(database);
  await createQrTable(database, "public", "public");
  await database.query(
    "INSERT INTO public.qr_code(plant_id, qr_code, status) VALUES(1, 'assigned-token', 'assigned')",
  );

  await runSql(database, legacyRepairMigration);
  await runSql(database, legacyRepairMigration);
  assert.equal((await foreignKey(database, "public.qr_code", "qr_code_plant_id_fkey")).parent,
    "plant_app.plant_record");

  await runMigration(database);
  assert.equal((await foreignKey(database, "plant_app.qr_code", "qr_code_plant_id_fkey")).parent,
    "plant_app.plant_record");
  assert.equal((await database.query(
    "SELECT qr_code FROM plant_app.qr_code WHERE plant_id=1",
  )).rows[0].qr_code, "assigned-token");
});

test("no inventory table creates the target design and plant foreign key", async (t) => {
  const database = await testPool();
  t.after(() => database.end());
  await createPlants(database, false);

  await runMigration(database);

  const created = (await database.query(`
    SELECT column_name, is_nullable, column_default, is_identity, identity_generation
    FROM information_schema.columns
    WHERE table_schema='plant_app' AND table_name='qr_code'
    ORDER BY ordinal_position
  `)).rows;
  assert.deepEqual(created.map((column) => column.column_name), [
    "qr_id", "plant_id", "qr_code", "status", "generated_at",
    "assigned_at", "activated_at", "retired_at",
  ]);
  assert.equal(created[0].is_identity, "YES");
  assert.equal(created[0].identity_generation, "BY DEFAULT");
  assert.equal(created[2].is_nullable, "NO");
  assert.equal(created[3].is_nullable, "NO");
  assert.equal(created[3].column_default, "'generated'::text");
  assert.equal(created[4].is_nullable, "NO");
  const qrForeignKey = await foreignKey(database, "plant_app.qr_code", "qr_code_plant_id_fkey");
  assert.equal(qrForeignKey.parent, "plant_app.plant_record");
  assert.equal(qrForeignKey.confdeltype, "n");

  await runInventoryMigration(database);
  await runInventoryMigration(database);
  const inventory = (await database.query(
    "SELECT plant_id, qr_code, status FROM plant_app.qr_code",
  )).rows;
  assert.equal(inventory.length, 1);
  assert.equal(inventory[0].plant_id, 1);
  assert.equal(inventory[0].qr_code, "assigned-token");
});

