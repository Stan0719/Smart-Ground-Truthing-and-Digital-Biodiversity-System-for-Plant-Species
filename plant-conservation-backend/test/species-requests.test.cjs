"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { readFileSync } = require("node:fs");
const { join } = require("node:path");
const { once } = require("node:events");
const sharp = require("sharp");
const { createPlantDatabase } = require("./postgres-fixture.cjs");
const { createPlantApp } = require("../server.js");

test("plant scientific-name migration preserves legacy rows and can be applied twice", async (t) => {
  const pool = await createPlantDatabase();
  t.after(() => pool.end());
  await pool.query("CREATE SCHEMA legacy_name_test; CREATE TABLE legacy_name_test.plant_record(plant_id INTEGER PRIMARY KEY); INSERT INTO legacy_name_test.plant_record VALUES(1)");
  const migration = readFileSync(join(__dirname, "../migrations/005-plant-scientific-name.sql"), "utf8")
    .replace(/^--[^\n]*\n/gm, "").replace(/^\s*BEGIN;\s*/i, "").replace(/\s*COMMIT;\s*$/i, "");
  for (let i = 0; i < 2; i++) {
    const c = await pool.connect();
    try {
      await c.query("BEGIN");
      await c.query("SET LOCAL search_path TO legacy_name_test");
      await c.query(migration);
      await c.query("COMMIT");
    } finally { c.release(); }
  }
  assert.equal((await pool.query("SELECT scientific_name FROM legacy_name_test.plant_record WHERE plant_id=1")).rows[0].scientific_name, null);
  await assert.rejects(pool.query("UPDATE legacy_name_test.plant_record SET scientific_name=' ' WHERE plant_id=1"), (error) => error.code === "23514");
});

test("species proposals remain separate from plants until officer approval", async (t) => {
  const pool = await createPlantDatabase();
  t.after(() => pool.end());
  const migration = readFileSync(join(__dirname, "../migrations/004-species-requests.sql"), "utf8");
  await pool.query(migration);
  await pool.query(migration); // Additive migration is repeatable.
  await pool.query(readFileSync(join(__dirname, "../migrations/006-atomic-plant-submissions.sql"), "utf8"));
  // Isolated QR fixture matches the pre-existing inventory contract; no production QR migration.
  await pool.query("CREATE TABLE public.qr_code(qr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,plant_id INTEGER,qr_code TEXT,status TEXT,generated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,assigned_at TIMESTAMPTZ,activated_at TIMESTAMPTZ,retired_at TIMESTAMPTZ)");
  const roles = { bot: "Botanist", other: "Botanist", officer: "Conservation Officer", visitor: "Visitor", admin: "Administrator" };
  const tokens = Object.fromEntries(Object.keys(roles).map((key, i) => [key, String(i + 1).repeat(64)]));
  const auth = { session: async (token) => {
    const key = Object.keys(tokens).find((key) => tokens[key] === token);
    return key ? { id: key, role: roles[key], status: "Active", mustChangePassword: false } : null;
  }, event: async () => {} };
  const server = createPlantApp({ pool, auth }).listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(async () => { server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); });
  const base = `http://127.0.0.1:${server.address().port}/api`;
  async function call(path, role = "bot", method = "GET", body) {
    const response = await fetch(base + path, { method,
      headers: { "Content-Type": "application/json", ...(tokens[role] ? { Authorization: `Bearer ${tokens[role]}` } : {}) },
      body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, data: response.headers.get("content-type")?.includes("json") ? await response.json() : Buffer.from(await response.arrayBuffer()) };
  }
  const image = await sharp({ create: { width: 4, height: 4, channels: 3, background: "green" } }).png().toBuffer();
  const proposal = { scientific_name: "Nepenthes mirabilis", common_name: "Swamp pitcher plant", genus_name: "Nepenthes", family_name: "Nepenthaceae", conservation_status: "Least Concern", description: "Pitchers on a climbing plant", habitat: "Wet lowland forest", photo: { content_type: "image/png", base64: image.toString("base64") }, client_key: "proposal-1" };
  let requestId;
  await t.test("all eight proposal fields are required, no plant fields are needed", async () => {
    for (const key of ["scientific_name", "common_name", "genus_name", "family_name", "conservation_status", "description", "habitat", "photo"]) {
      const invalid = { ...proposal }; delete invalid[key];
      assert.equal((await call("/species-requests", "bot", "POST", invalid)).status, 400, key);
    }
    const result = await call("/species-requests", "bot", "POST", proposal);
    assert.equal(result.status, 201, JSON.stringify(result.data));
    requestId = result.data.species_request.request_id;
    assert.equal(result.data.species_request.request_status, "Pending Review");
    assert.equal(result.data.species_request.approved_species_id, null);
    assert.equal((await pool.query("SELECT * FROM species")).rows.length, 0);
    assert.equal((await pool.query("SELECT * FROM plant_record")).rows.length, 0);
    assert.equal((await call("/species?scope=scientific")).data.species.length, 0);
  });
  await t.test("retries are idempotent, altered retries and duplicate names fail", async () => {
    assert.equal((await call("/species-requests", "bot", "POST", proposal)).data.species_request.request_id, requestId);
    assert.equal((await call("/species-requests", "bot", "POST", { ...proposal, common_name: "Changed" })).status, 409);
    assert.equal((await call("/species-requests", "other", "POST", { ...proposal, scientific_name: " NEPENTHES MIRABILIS ", client_key: "other" })).status, 409);
  });
  await t.test("ownership and officer-only review are enforced", async () => {
    assert.equal((await call("/species-requests", "visitor", "POST", proposal)).status, 403);
    assert.equal((await call("/species-requests", "admin")).status, 403);
    assert.equal((await call(`/species-requests/${requestId}`, "other")).status, 404);
    assert.equal((await call(`/species-requests/${requestId}/photo`, "other")).status, 404);
    assert.equal((await call("/species-requests", "other")).data.species_requests.length, 0);
    assert.equal((await call("/species-requests", "officer")).data.species_requests.length, 1);
    assert.equal((await call(`/species-requests/${requestId}/photo`, "officer")).status, 200);
    assert.equal((await call(`/species-requests/${requestId}/review`, "bot", "POST", { decision: "Approved", comment: "Checked", visibility: "internal" })).status, 403);
    roles.bot = "Conservation Officer";
    try {
      assert.equal((await call(`/species-requests/${requestId}/review`, "bot", "POST", { decision: "Approved", comment: "Self review", visibility: "internal" })).status, 403);
    } finally { roles.bot = "Botanist"; }
  });
  let speciesId;
  await t.test("explicit officer approval creates only a species and preserves distinct names and photo", async () => {
    const result = await call(`/species-requests/${requestId}/review`, "officer", "POST", { decision: "Approved", comment: "Taxonomy verified", visibility: "internal" });
    assert.equal(result.status, 200, JSON.stringify(result.data));
    speciesId = result.data.species_request.approved_species_id;
    const record = (await call(`/species/${speciesId}`)).data.species;
    assert.equal(record.scientific_name, proposal.scientific_name);
    assert.equal(record.common_name, proposal.common_name);
    assert.equal(record.genus_name, proposal.genus_name);
    assert.equal(record.family_name, proposal.family_name);
    assert.equal(record.habitat, proposal.habitat);
    assert.equal((await pool.query("SELECT * FROM plant_asset WHERE species_id=$1", [speciesId])).rows.length, 1);
    assert.equal((await pool.query("SELECT * FROM plant_record")).rows.length, 0);
    assert.equal((await call(`/species-requests/${requestId}/review`, "officer", "POST", { decision: "Approved", comment: "Again", visibility: "internal" })).status, 409);
    assert.equal((await call("/species-requests", "other", "POST", { ...proposal, client_key: "duplicate" })).status, 409);
    assert.equal((await call("/species", "officer", "POST", { scientific_name: proposal.scientific_name.toUpperCase(), common_name: "Another common name", description: "Duplicate", visibility: "public" })).status, 409);
  });
  await t.test("plant registration keeps species FK, QR assignment, location, photo upload and pending observation submission", async () => {
    await pool.query("INSERT INTO public.qr_code(qr_code,status) VALUES('existing-qr-token','generated')");
    const plant = { species_id: speciesId, scientific_name: "Individual field name", qr_id: 1, client_key: "plant-1", latitude: 4.5, longitude: 113.7,
      content: { heightCm: 80, healthStatus: "Healthy", lifeStage: "Juvenile", morphology: "Green leaves", notes: "", latitude: 4.5, longitude: 113.7, zone: "Zone A", altitudeM: 20 } };
    for (const change of [{ scientific_name: " " }, { scientific_name: 123 }, { scientific_name: "x".repeat(201) }, { species_id: 9999 }, { species_id: "request-1" }, { content: { ...plant.content, healthStatus: "" } }, { content: { ...plant.content, heightCm: 0 } }]) {
      assert.ok([400, 404].includes((await call("/plants", "bot", "POST", { ...plant, ...change })).status));
    }
    const created = await call("/plants", "bot", "POST", plant);
    assert.equal(created.status, 201, JSON.stringify(created.data));
    const { plant_id, id: observationId } = created.data;
    assert.equal(Number((await pool.query("SELECT species_id FROM plant_record WHERE plant_id=$1", [plant_id])).rows[0].species_id), Number(speciesId));
    assert.equal((await pool.query("SELECT status FROM public.qr_code WHERE qr_id=1")).rows[0].status, "assigned");
    assert.equal((await call(`/plants/${plant_id}/qr`)).data.qr_token, "existing-qr-token");
    assert.equal((await call("/assets", "bot", "POST", { plant_id, observation_id: observationId, client_key: "photo-1", content_type: "image/png", base64: image.toString("base64") })).status, 201);
    assert.equal((await call(`/observations/${observationId}/submit`, "bot", "POST", {})).status, 200);
    assert.equal((await pool.query("SELECT status,content FROM plant_observation WHERE id=$1", [observationId])).rows[0].status, "Pending Review");
    const record = (await call(`/plants/${plant_id}`)).data.plant;
    assert.equal(String(record.species_id), String(speciesId));
    assert.equal(record.scientific_name, "Individual field name");
    assert.equal((await pool.query("SELECT scientific_name FROM plant_record WHERE plant_id=$1", [plant_id])).rows[0].scientific_name, "Individual field name");
    assert.equal((await pool.query("SELECT scientific_name FROM species WHERE species_id=$1", [speciesId])).rows[0].scientific_name, proposal.scientific_name);
    assert.equal((await call("/plants", "bot", "POST", { ...plant, scientific_name: "Different retry name" })).status, 409);

  });
  await t.test("rejected requests never create species; invalid photos and supplied approval fields are rejected", async () => {
    assert.equal((await call("/species-requests", "bot", "POST", { ...proposal, scientific_name: "Other species", client_key: "invalid-photo", photo: { content_type: "image/png", base64: Buffer.from("not a photo").toString("base64") } })).status, 400);
    assert.equal((await call("/species-requests", "bot", "POST", { ...proposal, request_status: "Approved" })).status, 400);
    const result = await call("/species-requests", "bot", "POST", { ...proposal, scientific_name: "Other species", client_key: "rejected-1" });
    const review = await call(`/species-requests/${result.data.species_request.request_id}/review`, "officer", "POST", { decision: "Rejected", comment: "Identification unsupported" });
    assert.equal(review.status, 200);
    assert.equal(review.data.species_request.approved_species_id, null);
    assert.equal((await pool.query("SELECT * FROM species")).rows.length, 1);
  });
});
