test("plant scientific-name migration preserves legacy rows and can be applied twice", async (t) => {
  const pool = await createPlantDatabase();
  t.after(() => pool.end());
  await pool.query("CREATE SCHEMA legacy_name_test; CREATE TABLE legacy_name_test.plant_record(plant_id INTEGER PRIMARY KEY); INSERT INTO legacy_name_test.plant_record VALUES(1)");
  const migration = readFileSync(join(__dirname, "../migrations/005-plant-scientific-name.sql"), "utf8")
    .replace(/^--[^\n]*\n/gm, "").replace(/^\s*BEGIN;\s*/i, "").replace(/\s*COMMIT;\s*$/i, "");
  for (let i = 0; i < 2; i++) {
    const c = await pool.connect();
    try {
      await c.query("BEGIN");
      await c.query("SET LOCAL search_path TO legacy_name_test");
      await c.query(migration);
      await c.query("COMMIT");
    } finally { c.release(); }
  }
  assert.equal((await pool.query("SELECT scientific_name FROM legacy_name_test.plant_record WHERE plant_id=1")).rows[0].scientific_name, null);
  await assert.rejects(pool.query("UPDATE legacy_name_test.plant_record SET scientific_name=' ' WHERE plant_id=1"), (error) => error.code === "23514");
});

test("species proposals remain separate from plants until officer approval", async (t) => {
  const pool = await createPlantDatabase();
  t.after(() => pool.end());
  // Migration 017 selects plant_app; all fixture migrations must target the same schema.
  await pool.query("CREATE SCHEMA IF NOT EXISTS plant_app; SET search_path=plant_app,pg_catalog");
  await pool.query(readFileSync(join(__dirname, "../schema.postgres.sql"), "utf8"));
  const migration = readFileSync(join(__dirname, "../migrations/004-species-requests.sql"), "utf8");
  await pool.query(migration);
  await pool.query(migration); // Additive migration is repeatable.
  await pool.query(readFileSync(join(__dirname, "../migrations/006-atomic-plant-submissions.sql"), "utf8"));
  await pool.query(readFileSync(join(__dirname, "../migrations/016-species-request-content-revision.sql"), "utf8"));
  await pool.query(readFileSync(join(__dirname, "../migrations/017-species-review-cycle.sql"), "utf8"));
  for (const migrationFile of ["008-record-change-submissions.sql", "009-record-version-history.sql",
    "025-original-plant-withdrawal.sql", "026-original-species-withdrawal.sql"])
    await pool.query(readFileSync(join(__dirname, "../migrations", migrationFile), "utf8"));
  // Isolated QR fixture matches the pre-existing inventory contract; no production QR migration.
  await pool.query("CREATE TABLE plant_app.qr_code(qr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,plant_id INTEGER,qr_code TEXT,status TEXT,generated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,assigned_at TIMESTAMPTZ,activated_at TIMESTAMPTZ,retired_at TIMESTAMPTZ)");
  const roles = { bot: "Botanist", other: "Botanist", officer: "Conservation Officer", visitor: "Visitor", admin: "Administrator" };
  const tokens = Object.fromEntries(Object.keys(roles).map((key, i) => [key, String(i + 1).repeat(64)]));
  const auth = { session: async (token) => {
    const key = Object.keys(tokens).find((key) => tokens[key] === token);
    return key ? { id: key, role: roles[key], status: "Active", mustChangePassword: false } : null;
  }, event: async () => {} };
  const server = createPlantApp({ pool, auth }).listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(async () => { server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); });
  const base = `http://127.0.0.1:${server.address().port}/api`;
  async function call(path, role = "bot", method = "GET", body) {
    if (/^\/species-requests\/\d+\/review$/.test(path) && body && !Object.hasOwn(body, 'expected_revision')) {
      const row = (await pool.query('SELECT content_revision,review_cycle FROM species_request_submission WHERE request_id::text=$1', [path.split('/')[2]])).rows[0];
      body = { ...body, expected_review_cycle: row?.review_cycle || 1, expected_revision: row?.content_revision || 1 };
    }

    const response = await fetch(base + path, { method,
      headers: { "Content-Type": "application/json", ...(tokens[role] ? { Authorization: `Bearer ${tokens[role]}` } : {}) },
      body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, data: response.headers.get("content-type")?.includes("json") ? await response.json() : Buffer.from(await response.arrayBuffer()) };
  }
  const image = await sharp({ create: { width: 4, height: 4, channels: 3, background: "green" } }).png().toBuffer();
  const proposal = { scientific_name: "Nepenthes mirabilis", common_name: "Swamp pitcher plant", genus_name: "Nepenthes", family_name: "Nepenthaceae", conservation_status: "Least Concern", description: "Pitchers on a climbing plant", habitat: "Wet lowland forest", photo: { content_type: "image/png", base64: image.toString("base64") }, client_key: "proposal-1" };
  let requestId;
  await t.test("all eight proposal fields are required, no plant fields are needed", async () => {
    for (const key of ["scientific_name", "common_name", "genus_name", "family_name", "conservation_status", "description", "habitat", "photo"]) {
      const invalid = { ...proposal }; delete invalid[key];
      assert.equal((await call("/species-requests", "bot", "POST", invalid)).status, 400, key);
    }
    const result = await call("/species-requests", "bot", "POST", proposal);
    assert.equal(result.status, 201, JSON.stringify(result.data));
    requestId = result.data.species_request.request_id;
    assert.equal(result.data.species_request.request_status, "Pending Review");
    assert.equal(result.data.species_request.approved_species_id, null);
    assert.equal((await pool.query("SELECT * FROM species")).rows.length, 0);
    assert.equal((await pool.query("SELECT * FROM plant_record")).rows.length, 0);
    assert.equal((await call("/species?scope=scientific")).data.species.length, 0);
  });
  await t.test("retries are idempotent, altered retries and duplicate names fail", async () => {
    assert.equal((await call("/species-requests", "bot", "POST", proposal)).data.species_request.request_id, requestId);
    assert.equal((await call("/species-requests", "bot", "POST", { ...proposal, common_name: "Changed" })).status, 409);
    const ownDuplicate = await call("/species-requests", "bot", "POST", { ...proposal,
      scientific_name: " NEPENTHES   MIRABILIS ", client_key: "own-normalized-duplicate" });
    assert.equal(ownDuplicate.status, 409);
    assert.equal(ownDuplicate.data.code, "SPECIES_DUPLICATE_PENDING");
    assert.equal(String(ownDuplicate.data.request_id), String(requestId));
    const privateDuplicate = await call("/species-requests", "other", "POST", { ...proposal,
      scientific_name: " NEPENTHES MIRABILIS ", client_key: "other" });
    assert.equal(privateDuplicate.status, 409);
    assert.equal(privateDuplicate.data.code, "SPECIES_DUPLICATE_PENDING");
    assert.equal(privateDuplicate.data.request_id, undefined, "do not reveal another Botanist's request identifier");
    assert.equal(privateDuplicate.data.request_status, undefined);
    await pool.query("UPDATE species_request_submission SET request_status='Correction Required' WHERE request_id=$1", [requestId]);
    const correctionDuplicate = await call("/species-requests", "bot", "POST", { ...proposal,
      scientific_name: "Nepenthes MIRABILIS", client_key: "correction-duplicate" });
    assert.equal(correctionDuplicate.status, 409);
    assert.equal(correctionDuplicate.data.code, "SPECIES_DUPLICATE_CORRECTION");
    assert.equal(String(correctionDuplicate.data.request_id), String(requestId));
    const privateCorrection = await call("/species-requests", "other", "POST", { ...proposal,
      scientific_name: "Nepenthes mirabilis", client_key: "private-correction-duplicate" });
    assert.equal(privateCorrection.status, 409);
    assert.equal(privateCorrection.data.code, "SPECIES_DUPLICATE_PENDING");
    assert.equal(privateCorrection.data.duplicate_type, "pending");
    assert.equal(privateCorrection.data.request_id, undefined);
    assert.equal(privateCorrection.data.request_status, undefined);
    await pool.query("UPDATE species_request_submission SET request_status='Pending Review' WHERE request_id=$1", [requestId]);
  });
  await t.test("ownership and officer-only review are enforced", async () => {
    assert.equal((await call("/species-requests", "visitor", "POST", proposal)).status, 403);
    assert.equal((await call("/species-requests", "admin")).status, 403);
    assert.equal((await call(`/species-requests/${requestId}`, "other")).status, 404);
    assert.equal((await call(`/species-requests/${requestId}/photo`, "other")).status, 404);
    assert.equal((await call("/species-requests", "other")).data.species_requests.length, 0);
    assert.equal((await call("/species-requests", "officer")).data.species_requests.length, 1);
    assert.equal((await call(`/species-requests/${requestId}/photo`, "officer")).status, 200);
    assert.equal((await call(`/species-requests/${requestId}/review`, "bot", "POST", { decision: "Approved", comment: "Checked", visibility: "internal" })).status, 403);
    roles.bot = "Conservation Officer";
    try {
      assert.equal((await call(`/species-requests/${requestId}/review`, "bot", "POST", { decision: "Approved", comment: "Self review", visibility: "internal" })).status, 403);
    } finally { roles.bot = "Botanist"; }
  });
  let speciesId;
  await t.test("explicit officer approval creates only a species and preserves distinct names and photo", async () => {
    const result = await call(`/species-requests/${requestId}/review`, "officer", "POST", { decision: "Approved", comment: "Taxonomy verified", visibility: "internal" });
    assert.equal(result.status, 200, JSON.stringify(result.data));
    speciesId = result.data.species_request.approved_species_id;
    const record = (await call(`/species/${speciesId}`)).data.species;
    assert.equal(record.scientific_name, proposal.scientific_name);
    assert.equal(record.common_name, proposal.common_name);
    assert.equal(record.genus_name, proposal.genus_name);
    assert.equal(record.family_name, proposal.family_name);
    assert.equal(record.habitat, proposal.habitat);
    assert.equal((await pool.query("SELECT * FROM plant_asset WHERE species_id=$1", [speciesId])).rows.length, 1);
    assert.equal((await pool.query("SELECT * FROM plant_record")).rows.length, 0);
    assert.equal((await call(`/species-requests/${requestId}/review`, "officer", "POST", { decision: "Approved", comment: "Again", visibility: "internal" })).status, 409);
    assert.equal((await call("/species-requests", "other", "POST", { ...proposal, client_key: "duplicate" })).status, 409);
    const normalizedDuplicate = await call("/species-requests", "bot", "POST", { ...proposal,
      scientific_name: "  NEPENTHES   MIRABILIS  ", client_key: "normalized-duplicate" });
    assert.equal(normalizedDuplicate.status, 409);
    assert.equal(normalizedDuplicate.data.code, "SPECIES_DUPLICATE_APPROVED");
    assert.equal(String(normalizedDuplicate.data.species_id), String(speciesId));
    assert.equal((await call("/species", "officer", "POST", { scientific_name: proposal.scientific_name.toUpperCase(), common_name: "Another common name", description: "Duplicate", visibility: "public" })).status, 409);
  });
  await t.test("plant registration keeps species FK, QR assignment, location, photo upload and pending observation submission", async () => {
    await pool.query("INSERT INTO plant_app.qr_code(qr_code,status) VALUES('existing-qr-token','generated')");
    const plant = { species_id: speciesId, scientific_name: "Individual field name", qr_id: 1, client_key: "plant-1", latitude: 4.5, longitude: 113.7,
      content: { heightCm: 80, healthStatus: "Healthy", lifeStage: "Juvenile", morphology: "Green leaves", notes: "", latitude: 4.5, longitude: 113.7, zone: "Zone A", altitudeM: 20 } };
    for (const change of [{ scientific_name: " " }, { scientific_name: 123 }, { scientific_name: "x".repeat(201) }, { species_id: 9999 }, { species_id: "request-1" }, { content: { ...plant.content, healthStatus: "" } }, { content: { ...plant.content, heightCm: 0 } }]) {
      assert.ok([400, 404].includes((await call("/plants", "bot", "POST", { ...plant, ...change })).status));
    }
    const created = await call("/plants", "bot", "POST", plant);
    assert.equal(created.status, 201, JSON.stringify(created.data));
    const { plant_id, id: observationId } = created.data;
    assert.equal(Number((await pool.query("SELECT species_id FROM plant_record WHERE plant_id=$1", [plant_id])).rows[0].species_id), Number(speciesId));
    assert.equal((await pool.query("SELECT status FROM plant_app.qr_code WHERE qr_id=1")).rows[0].status, "assigned");
    assert.equal((await call(`/plants/${plant_id}/qr`)).data.qr_token, "existing-qr-token");
    assert.equal((await call("/assets", "bot", "POST", { plant_id, observation_id: observationId, client_key: "photo-1", content_type: "image/png", base64: image.toString("base64") })).status, 201);
    assert.equal((await call(`/observations/${observationId}/submit`, "bot", "POST", {})).status, 200);
    assert.equal((await pool.query("SELECT status,content FROM plant_observation WHERE id=$1", [observationId])).rows[0].status, "Pending Review");
    const record = (await call(`/plants/${plant_id}`)).data.plant;
    assert.equal(String(record.species_id), String(speciesId));
    assert.equal(record.scientific_name, "Individual field name");
    assert.equal((await pool.query("SELECT scientific_name FROM plant_record WHERE plant_id=$1", [plant_id])).rows[0].scientific_name, "Individual field name");
    assert.equal((await pool.query("SELECT scientific_name FROM species WHERE species_id=$1", [speciesId])).rows[0].scientific_name, proposal.scientific_name);
    assert.equal((await call("/plants", "bot", "POST", { ...plant, scientific_name: "Different retry name" })).status, 409);

  });
  await t.test("rejected requests never create species; invalid photos and supplied approval fields are rejected", async () => {
    assert.equal((await call("/species-requests", "bot", "POST", { ...proposal, scientific_name: "Other species", client_key: "invalid-photo", photo: { content_type: "image/png", base64: Buffer.from("not a photo").toString("base64") } })).status, 400);
    assert.equal((await call("/species-requests", "bot", "POST", { ...proposal, request_status: "Approved" })).status, 400);
    const result = await call("/species-requests", "bot", "POST", { ...proposal, scientific_name: "Other species", client_key: "rejected-1" });
    const review = await call(`/species-requests/${result.data.species_request.request_id}/review`, "officer", "POST", { decision: "Rejected", comment: "Identification unsupported" });
    assert.equal(review.status, 200);
    assert.equal(review.data.species_request.approved_species_id, null);
    assert.equal((await pool.query("SELECT * FROM species")).rows.length, 1);
  });
  await t.test("concurrent normalized duplicate submissions create only one active request", async () => {
    const requests = await Promise.all([
      call("/species-requests", "bot", "POST", { ...proposal, scientific_name: "Concurrent exact species", client_key: "concurrent-a" }),
      call("/species-requests", "bot", "POST", { ...proposal, scientific_name: "  CONCURRENT   EXACT SPECIES  ", client_key: "concurrent-b" }),
    ]);
    assert.deepEqual(requests.map((result) => result.status).sort(), [201, 409]);
    assert.equal((await pool.query("SELECT count(*)::integer AS count FROM species_request_submission WHERE lower(regexp_replace(btrim(normalize(scientific_name,NFC)),'[[:space:]]+',' ','g'))=lower(regexp_replace(btrim(normalize('Concurrent exact species',NFC)),'[[:space:]]+',' ','g')) AND request_status='Pending Review'")).rows[0].count, 1);
  });
  await t.test("a rejected request does not block a new active request with the same normalized name", async () => {
    const rejected = await call("/species-requests", "bot", "POST", { ...proposal, scientific_name: "Rejected name retry", client_key: "rejected-before" });
    assert.equal(rejected.status, 201, JSON.stringify(rejected.data));
    await pool.query("UPDATE species_request_submission SET request_status='Rejected' WHERE request_id=$1", [rejected.data.species_request.request_id]);
    const retry = await call("/species-requests", "bot", "POST", { ...proposal, scientific_name: " REJECTED   NAME RETRY ", client_key: "rejected-after" });
    assert.equal(retry.status, 201, JSON.stringify(retry.data));
    assert.notEqual(String(retry.data.species_request.request_id), String(rejected.data.species_request.request_id));
  });
  await t.test("database duplicate lookup treats canonically equivalent Unicode names as equal", async () => {
    const composed = await call("/species-requests", "bot", "POST", { ...proposal,
      scientific_name: "Café plant", client_key: "unicode-composed" });
    assert.equal(composed.status, 201, JSON.stringify(composed.data));
    const decomposed = await call("/species-requests", "bot", "POST", { ...proposal,
      scientific_name: "Cafe\u0301 plant", client_key: "unicode-decomposed" });
    assert.equal(decomposed.status, 409);
    assert.equal(decomposed.data.code, "SPECIES_DUPLICATE_PENDING");
    assert.equal(String(decomposed.data.request_id), String(composed.data.species_request.request_id));
    const spaced = await call("/species-requests", "bot", "POST", { ...proposal,
      scientific_name: "Agave sisalana", client_key: "unicode-space-base" });
    assert.equal(spaced.status, 201, JSON.stringify(spaced.data));
    const nonBreakingSpace = await call("/species-requests", "bot", "POST", { ...proposal,
      scientific_name: "Agave\u00a0sisalana", client_key: "unicode-space-duplicate" });
    assert.equal(nonBreakingSpace.status, 409);
    assert.equal(nonBreakingSpace.data.code, "SPECIES_DUPLICATE_PENDING");
  });
  await t.test("Species request withdrawal ignores withdrawn Plant history but protects active links", async () => {
    const standalone = await call("/species-requests", "bot", "POST", { ...proposal,
      scientific_name: "Standalone withdrawal test", client_key: "standalone-withdrawal-test" });
    assert.equal(standalone.status, 201, JSON.stringify(standalone.data));
    const standaloneId = standalone.data.species_request.request_id;
    assert.equal((await call(`/species-requests/${standaloneId}/withdraw`, "other", "POST", {})).status, 404,
      "another Botanist cannot withdraw this pending request");
    assert.equal((await pool.query("SELECT request_status FROM species_request_submission WHERE request_id=$1", [standaloneId])).rows[0].request_status, "Pending Review");
    const standaloneWithdrawn = await call(`/species-requests/${standaloneId}/withdraw`, "bot", "POST", {});
    assert.equal(standaloneWithdrawn.status, 200, JSON.stringify(standaloneWithdrawn.data));
    assert.equal(standaloneWithdrawn.data.species_request.request_status, "Withdrawn");

    const result = await call("/species-requests", "bot", "POST", { ...proposal,
      scientific_name: "Withdrawal link test", client_key: "withdrawal-link-test" });
    assert.equal(result.status, 201, JSON.stringify(result.data));
    const linkedRequestId = result.data.species_request.request_id;
    const linkedSpecies = (await pool.query(`INSERT INTO species(scientific_name,common_name,genus_id,status_id,description,rbac_data)
      SELECT 'Withdrawal link test','Test species',genus_id,status_id,'fixture', '{"approvalStatus":"Pending Review"}'::jsonb
      FROM species WHERE species_id=$1 RETURNING species_id`, [speciesId])).rows[0].species_id;
    await pool.query("UPDATE species_request_submission SET proposed_species_id=$2 WHERE request_id=$1", [linkedRequestId, linkedSpecies]);
    const plant = (await pool.query(`INSERT INTO plant_record(species_id,registered_subject,rbac_status,qr_token)
      VALUES($1,'staff:bot','Pending Review','withdrawal-linked-plant') RETURNING plant_id`, [linkedSpecies])).rows[0];
    await pool.query(`INSERT INTO plant_observation(id,plant_id,owner_subject,status,content,client_key,origin_type)
      VALUES('withdrawal-linked-observation',$1,'staff:bot','Pending Review','{}'::jsonb,'withdrawal-linked-observation','initial_registration')`, [plant.plant_id]);

    const blocked = await call(`/species-requests/${linkedRequestId}/withdraw`, "bot", "POST", {});
    assert.equal(blocked.status, 409, "an active Plant still prevents withdrawing its referenced Species proposal");
    assert.equal((await pool.query("SELECT request_status FROM species_request_submission WHERE request_id=$1", [linkedRequestId])).rows[0].request_status, "Pending Review");

    await pool.query("UPDATE plant_record SET rbac_status='Withdrawn',withdrawn_by='staff:bot',withdrawn_at=CURRENT_TIMESTAMP WHERE plant_id=$1", [plant.plant_id]);
    const withdrawn = await call(`/species-requests/${linkedRequestId}/withdraw`, "bot", "POST", {});
    assert.equal(withdrawn.status, 200, JSON.stringify(withdrawn.data));
    assert.equal(withdrawn.data.species_request.request_status, "Withdrawn");
    assert.equal((await pool.query("SELECT count(*)::integer AS count FROM plant_record WHERE plant_id=$1 AND species_id=$2", [plant.plant_id, linkedSpecies])).rows[0].count, 1);
    assert.equal((await pool.query("SELECT count(*)::integer AS count FROM plant_observation WHERE id='withdrawal-linked-observation' AND plant_id=$1", [plant.plant_id])).rows[0].count, 1);
    assert.equal((await pool.query("SELECT rbac_data->>'approvalStatus' AS status FROM species WHERE species_id=$1", [linkedSpecies])).rows[0].status, "Withdrawn");

  });
});
