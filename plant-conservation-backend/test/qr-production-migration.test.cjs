"use strict";

// These tests target only the disposable PostgreSQL fixture returned by the
// existing test helper. They are authored for a later approved rehearsal and
// were not executed during readiness-package preparation.
const test = require("node:test");
const assert = require("node:assert/strict");
const { readFileSync } = require("node:fs");
const { join } = require("node:path");

const migration = readFileSync(
  join(__dirname, "../migrations/016-production-qr-schema-move.sql"),
  "utf8",
);
const rollbackAsTransaction = migration.replace(/COMMIT;\s*$/, "ROLLBACK;");
const auditSql = readFileSync(
  join(__dirname, "../scripts/qr-production-readonly-checks.sql"),
  "utf8",
);
const reverseMigration = readFileSync(
  join(__dirname, "../migrations/016-production-qr-schema-move-rollback.sql"),
  "utf8",
);

async function testPool() {
  return (await import("../../web/server/test-postgres.mjs")).testPool();
}

async function createProductionShapeFixture(db) {
  await db.query(`
    CREATE SCHEMA plant_app;
    CREATE TABLE plant_app.plant_record (
      plant_id BIGINT PRIMARY KEY
    );
    INSERT INTO plant_app.plant_record(plant_id)
      SELECT generate_series(1, 18)::BIGINT;
    CREATE TABLE public.qr_code (
      qr_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      plant_id BIGINT UNIQUE
        REFERENCES plant_app.plant_record(plant_id) ON DELETE SET NULL,
      qr_code TEXT NOT NULL UNIQUE,
      status VARCHAR(30) NOT NULL DEFAULT 'generated',
      generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      assigned_at TIMESTAMPTZ,
      activated_at TIMESTAMPTZ,
      retired_at TIMESTAMPTZ
    );
    INSERT INTO public.qr_code(plant_id, qr_code, status, assigned_at)
      SELECT plant_id, 'fixture-token-' || plant_id, 'assigned', CURRENT_TIMESTAMP
      FROM plant_app.plant_record ORDER BY plant_id;
    CREATE TABLE public.qr_scan_history (
      scan_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
      qr_id BIGINT,
      CONSTRAINT qr_scan_history_qr_id_fkey
        FOREIGN KEY (qr_id) REFERENCES public.qr_code(qr_id) ON DELETE CASCADE
    );
    CREATE TABLE plant_app.visitor_scan_history (
      scan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      qr_id BIGINT,
      CONSTRAINT visitor_scan_history_qr_id_fkey
        FOREIGN KEY (qr_id) REFERENCES public.qr_code(qr_id) ON DELETE SET NULL
    );
    INSERT INTO plant_app.visitor_scan_history(qr_id)
      SELECT qr_id FROM public.qr_code ORDER BY qr_id;
    GRANT SELECT ON public.qr_code TO PUBLIC;
    GRANT USAGE, SELECT ON SEQUENCE public.qr_code_qr_id_seq TO PUBLIC;
  `);
}

async function state(db, qrName) {
  const qualified = `'${qrName}'::regclass`;
  return (await db.query(`
    SELECT c.oid::BIGINT AS table_oid,
           c.relowner::BIGINT AS table_owner,
           c.relacl::TEXT AS table_acl,
           c.relrowsecurity AS rls_enabled,
           c.relforcerowsecurity AS rls_forced,
           pg_get_serial_sequence(${qualified}::TEXT, 'qr_id') AS sequence_name,
           s.oid::BIGINT AS sequence_oid,
           s.relowner::BIGINT AS sequence_owner,
           s.relacl::TEXT AS sequence_acl,
           (SELECT count(*)::BIGINT FROM ${qrName}) AS qr_rows,
           (SELECT count(*)::BIGINT FROM plant_app.visitor_scan_history) AS visitor_rows,
           (SELECT count(*)::BIGINT FROM public.qr_scan_history) AS public_scan_rows
    FROM pg_class c
    LEFT JOIN pg_class s
      ON s.oid = to_regclass(pg_get_serial_sequence(${qualified}::TEXT, 'qr_id'))
    WHERE c.oid = ${qualified}
  `)).rows[0];
}

test("production move preserves the 18/18/0 inventory and object security state", async (t) => {
  const db = await testPool();
  t.after(() => db.end());
  await createProductionShapeFixture(db);

  const before = await state(db, "public.qr_code");
  assert.equal(Number(before.qr_rows), 18);
  assert.equal(Number(before.visitor_rows), 18);
  assert.equal(Number(before.public_scan_rows), 0);
  await db.query(migration);

  assert.equal((await db.query("SELECT to_regclass('public.qr_code') IS NULL AS absent")).rows[0].absent, true);
  const after = await state(db, "plant_app.qr_code");
  assert.equal(after.table_oid, before.table_oid);
  assert.equal(Number(after.qr_rows), 18);
  assert.equal(Number(after.visitor_rows), 18);
  assert.equal(Number(after.public_scan_rows), 0);
  assert.equal(after.table_owner, before.table_owner);
  assert.equal(after.table_acl, before.table_acl);
  assert.equal(after.rls_enabled, false);
  assert.equal(after.rls_forced, false);
  assert.equal(after.sequence_oid, before.sequence_oid);
  assert.equal(after.sequence_owner, before.sequence_owner);
  assert.equal(after.sequence_acl, before.sequence_acl);
  assert.match(after.sequence_name, /^plant_app\./);

  const foreignKeys = (await db.query(`
    SELECT child_ns.nspname AS child_schema, c.conname,
           parent_ns.nspname AS parent_schema, parent.relname AS parent_table,
           c.confdeltype AS delete_action, c.confupdtype AS update_action,
           c.convalidated AS validated
    FROM pg_constraint c
    JOIN pg_class child ON child.oid = c.conrelid
    JOIN pg_namespace child_ns ON child_ns.oid = child.relnamespace
    JOIN pg_class parent ON parent.oid = c.confrelid
    JOIN pg_namespace parent_ns ON parent_ns.oid = parent.relnamespace
    WHERE c.contype = 'f'
      AND (c.conrelid = 'plant_app.qr_code'::regclass
        OR c.confrelid = 'plant_app.qr_code'::regclass)
    ORDER BY c.conname
  `)).rows;
  assert.deepEqual(foreignKeys.map((row) => [row.child_schema, row.conname, row.parent_schema, row.parent_table, row.delete_action, row.validated]), [
    ["plant_app", "qr_code_plant_id_fkey", "plant_app", "plant_record", "n", true],
    ["public", "qr_scan_history_qr_id_fkey", "plant_app", "qr_code", "c", true],
    ["plant_app", "visitor_scan_history_qr_id_fkey", "plant_app", "qr_code", "n", true],
  ]);
});

test("production move transaction can be aborted without changing the source location", async (t) => {
  const db = await testPool();
  t.after(() => db.end());
  await createProductionShapeFixture(db);
  const before = await state(db, "public.qr_code");

  await db.query(rollbackAsTransaction);

  assert.equal((await db.query("SELECT to_regclass('public.qr_code') IS NOT NULL AS present")).rows[0].present, true);
  assert.equal((await db.query("SELECT to_regclass('plant_app.qr_code') IS NULL AS absent")).rows[0].absent, true);
  const after = await state(db, "public.qr_code");
  assert.equal(after.table_oid, before.table_oid);
  assert.equal(Number(after.qr_rows), 18);
  assert.equal(Number(after.visitor_rows), 18);
  assert.equal(after.table_owner, before.table_owner);
  assert.equal(after.table_acl, before.table_acl);
  assert.equal(after.sequence_oid, before.sequence_oid);
  assert.equal(after.sequence_owner, before.sequence_owner);
  assert.equal(after.sequence_acl, before.sequence_acl);
});

test("reverse move retains the table OID and all current QR/history rows", async (t) => {
  const db = await testPool();
  t.after(() => db.end());
  await createProductionShapeFixture(db);
  await db.query(migration);
  const before = await state(db, "plant_app.qr_code");

  await db.query(reverseMigration);

  assert.equal((await db.query("SELECT to_regclass('plant_app.qr_code') IS NULL AS absent")).rows[0].absent, true);
  const after = await state(db, "public.qr_code");
  assert.equal(after.table_oid, before.table_oid);
  assert.equal(Number(after.qr_rows), Number(before.qr_rows));
  assert.equal(Number(after.visitor_rows), Number(before.visitor_rows));
  assert.equal(Number(after.public_scan_rows), Number(before.public_scan_rows));
  assert.equal(after.table_owner, before.table_owner);
  assert.equal(after.table_acl, before.table_acl);
  assert.equal(after.sequence_oid, before.sequence_oid);
  assert.equal(after.sequence_owner, before.sequence_owner);
  assert.equal(after.sequence_acl, before.sequence_acl);
  assert.match(after.sequence_name, /^public\./);
});

test("production readiness audit is read-only and checks the connection role and exposure", () => {
  assert.match(auditSql, /SELECT current_database\(\).*session_user AS login_role.*current_user AS effective_role/s);
  assert.match(auditSql, /has_schema_privilege/);
  assert.match(auditSql, /has_table_privilege/);
  assert.match(auditSql, /has_sequence_privilege/);
  assert.match(auditSql, /pgrst\.db_schemas/);
  assert.doesNotMatch(auditSql, /^\s*(?:INSERT|UPDATE|DELETE|CREATE|ALTER|DROP|TRUNCATE|GRANT|REVOKE|CALL|DO)\b/im);
});
