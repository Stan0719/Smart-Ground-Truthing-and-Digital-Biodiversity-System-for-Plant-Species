"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { once } = require("node:events");
const { createPlantDatabase } = require("./postgres-fixture.cjs");
const { createPlantApp } = require("../server.js");

test("Species 6 list includes distinct owner-visible Botanist records and only approved public Visitor records", async (t) => {
  const pool = await createPlantDatabase();
  t.after(() => pool.end());
  await pool.query(`INSERT INTO species(species_id,scientific_name) VALUES
    (6,'Species Six')`);
  await pool.query("INSERT INTO rbac_species_visibility(species_id,visibility) VALUES(6,'public')");
  await pool.query(`INSERT INTO plant_record(plant_id,species_id,registered_subject,rbac_status,qr_token) VALUES
    (8,6,'staff:botA','Approved','plant-8'),(11,6,'staff:botA','Pending Review','plant-11'),
    (13,6,'staff:botA','Pending Review','plant-13'),(14,6,'staff:botB','Pending Review','plant-14'),
    (15,6,'staff:botB','Pending Review','plant-15'),(17,6,'staff:botA','Pending Review','plant-17')`);
  await pool.query(`INSERT INTO plant_observation(id,plant_id,owner_subject,status,content,client_key) VALUES
    ('approved-8',8,'staff:botA','Approved','{"heightCm":10,"lifeStage":"Mature"}','a8'),
    ('rejected-8',8,'staff:botA','Rejected','{"heightCm":99,"lifeStage":"Pending edit"}','r8'),
    ('rejected-11',11,'staff:botA','Rejected','{}','r11'),
    ('pending-13',13,'staff:botA','Pending Review','{}','p13'),
    ('pending-14',14,'staff:botB','Pending Review','{}','p14'),
    ('correction-15',15,'staff:botB','Correction Required','{}','c15'),
    ('pending-17',17,'staff:botA','Pending Review','{}','p17')`);
  await pool.query(`INSERT INTO plant_observation(id,plant_id,owner_subject,status,content,client_key,created_at,updated_at)
    VALUES('approved-8-current',8,'staff:botA','Approved','{"heightCm":10,"lifeStage":"Mature"}','a8-current',NOW()+INTERVAL '1 second',NOW()+INTERVAL '1 second')`);
  await pool.query(`INSERT INTO plant_asset(id,plant_id,owner_subject,client_key,observation_id,approved,content_type,content) VALUES
    ('asset-8-approved',8,'staff:botA','asset-8','approved-8',false,'image/jpeg',decode('ffd8ff','hex')),
    ('asset-8-current',8,'staff:botA','asset-8-current','approved-8-current',false,'image/jpeg',decode('ffd8ff','hex')),
    ('asset-11-owner',11,'staff:botA','asset-11','rejected-11',false,'image/jpeg',decode('ffd8ff','hex')),
    ('asset-13-owner',13,'staff:botA','asset-13','pending-13',false,'image/jpeg',decode('ffd8ff','hex')),
    ('asset-17-owner',17,'staff:botA','asset-17','pending-17',false,'image/jpeg',decode('ffd8ff','hex'))`);
  await pool.query(`CREATE TABLE public.qr_code(
    qr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id INTEGER UNIQUE REFERENCES plant_record(plant_id),
    qr_code TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'generated'
  )`);

  const roles = { botA: "Botanist", botB: "Botanist", visitor: "Visitor" };
  const tokens = Object.fromEntries(Object.keys(roles).map((key, index) => [key, String(index + 1).repeat(64)]));
  const auth = {
    session: async (token) => {
      const key = Object.keys(tokens).find((candidate) => tokens[candidate] === token);
      return key ? { id: key, role: roles[key], status: "Active", mustChangePassword: false } : null;
    },
    event: async () => {},
  };
  const server = createPlantApp({ auth, pool, origins: new Set() }).listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(() => new Promise((resolve) => {
    server.closeAllConnections(); server.close(resolve);
  }));
  async function getPlants(account) {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api/plants`, {
      headers: { Authorization: `Bearer ${tokens[account]}` },
    });
    return (await response.json()).plants.filter((plant) => String(plant.species_id) === "6");
  }

  const botA = await getPlants("botA");
  const botB = await getPlants("botB");
  const visitor = await getPlants("visitor");
  assert.deepEqual(botA.map((plant) => String(plant.plant_id)).sort(), ["11", "13", "17", "8"]);
  assert.deepEqual(botB.map((plant) => String(plant.plant_id)).sort(), ["14", "15", "8"]);
  assert.deepEqual(visitor.map((plant) => String(plant.plant_id)), ["8"]);
  assert.equal(new Set(botA.map((plant) => String(plant.plant_id))).size, botA.length);
  assert.equal(botA.find((plant) => String(plant.plant_id) === "8").latest_approved.heightCm, 10);
  assert.equal(botA.find((plant) => String(plant.plant_id) === "8").latest_approved.lifeStage, "Mature");
  assert.equal(botA.find((plant) => String(plant.plant_id) === "8").plant_image_asset_id, "asset-8-current");
  assert.equal(botA.find((plant) => String(plant.plant_id) === "11").plant_image_asset_id, null);
  assert.equal(botA.find((plant) => String(plant.plant_id) === "13").plant_image_asset_id, "asset-13-owner");
  assert.equal(botA.find((plant) => String(plant.plant_id) === "17").plant_image_asset_id, "asset-17-owner");
  assert.equal(visitor[0].plant_image_asset_id, "asset-8-current");
  async function getPlantPhotos(account, plantId, scope = "") {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api/assets?plant_id=${plantId}${scope}`, {
      headers: { Authorization: `Bearer ${tokens[account]}` },
    });
    return (await response.json()).assets;
  }
  assert.deepEqual(await getPlantPhotos("botA", 11, "&scope=mine"), []);
  assert.deepEqual(await getPlantPhotos("visitor", 11, "&scope=mine"), []);
  assert.deepEqual((await getPlantPhotos("visitor", 8)).map((asset) => asset.id), ["asset-8-current"]);
  async function getAsset(account, assetId, scope = "") {
    return fetch(`http://127.0.0.1:${server.address().port}/api/assets/${assetId}${scope}`, {
      headers: { Authorization: `Bearer ${tokens[account]}` },
    });
  }
  assert.equal((await getAsset("visitor", "asset-8-current")).status, 200);
  assert.equal((await getAsset("visitor", "asset-8-approved")).status, 404);
  assert.equal((await getAsset("botA", "asset-13-owner", "?scope=mine")).status, 200);
  assert.equal((await getAsset("botA", "asset-11-owner", "?scope=mine")).status, 404);
});
