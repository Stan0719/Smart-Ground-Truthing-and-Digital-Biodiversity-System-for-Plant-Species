"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { once } = require("node:events");
const { createPlantDatabase } = require("./postgres-fixture.cjs");
const { createPlantApp } = require("../server.js");

test("Species 6 list includes distinct owner-visible Botanist records and only approved public Visitor records", async (t) => {
  const pool = await createPlantDatabase();
  t.after(() => pool.end());
  await pool.query(`INSERT INTO species(species_id,scientific_name) VALUES
    (6,'Species Six'),(7,'Owner Pending Species')`);
  await pool.query("UPDATE species SET common_name='Owner pending common name',rbac_data=$1 WHERE species_id=7", [{ habitat: 'Limestone forest', approvalStatus: 'Pending Review', submittedBy: 'staff:botA' }]);
  await pool.query("INSERT INTO rbac_species_visibility(species_id,visibility) VALUES(6,'public')");
  await pool.query("INSERT INTO rbac_species_visibility(species_id,visibility) VALUES(7,'protected')");
  await pool.query(`INSERT INTO plant_record(plant_id,species_id,registered_subject,rbac_status,qr_token) VALUES
    (8,6,'staff:botA','Approved','plant-8'),(11,6,'staff:botA','Pending Review','plant-11'),
    (13,6,'staff:botA','Pending Review','plant-13'),(14,6,'staff:botB','Pending Review','plant-14'),
    (15,6,'staff:botB','Pending Review','plant-15'),(17,6,'staff:botA','Pending Review','plant-17'),
    (18,6,'staff:botA','Rejected','plant-18'),(19,6,'staff:botA','Correction Required','plant-19'),
    (20,7,'staff:botA','Pending Review','plant-20')`);
  await pool.query(`INSERT INTO plant_observation(id,plant_id,owner_subject,status,content,client_key) VALUES
    ('approved-8',8,'staff:botA','Approved','{"heightCm":10,"lifeStage":"Mature"}','a8'),
    ('rejected-8',8,'staff:botA','Rejected','{"heightCm":99,"lifeStage":"Pending edit"}','r8'),
    ('rejected-11',11,'staff:botA','Rejected','{}','r11'),
    ('pending-13',13,'staff:botA','Pending Review','{"latitude":11.1,"longitude":22.2,"accuracy_m":5,"altitudeM":30,"zone":"Zone B"}','p13'),
    ('pending-14',14,'staff:botB','Pending Review','{}','p14'),
    ('correction-15',15,'staff:botB','Correction Required','{}','c15'),
    ('pending-17',17,'staff:botA','Pending Review','{}','p17'),
    ('pending-20',20,'staff:botA','Pending Review','{"heightCm":22,"lifeStage":"Seedling","notes":"Submitted plant notes"}','p20')`);
  await pool.query(`INSERT INTO plant_observation(id,plant_id,owner_subject,status,content,client_key,created_at,updated_at)
    VALUES('approved-8-current',8,'staff:botA','Approved','{"heightCm":10,"lifeStage":"Mature"}','a8-current',NOW()+INTERVAL '1 second',NOW()+INTERVAL '1 second')`);
  await pool.query(`INSERT INTO plant_asset(id,plant_id,owner_subject,client_key,observation_id,approved,content_type,content) VALUES
    ('asset-8-approved',8,'staff:botA','asset-8','approved-8',false,'image/jpeg',decode('ffd8ff','hex')),
    ('asset-8-current',8,'staff:botA','asset-8-current','approved-8-current',false,'image/jpeg',decode('ffd8ff','hex')),
    ('asset-11-owner',11,'staff:botA','asset-11','rejected-11',false,'image/jpeg',decode('ffd8ff','hex')),
    ('asset-13-owner',13,'staff:botA','asset-13','pending-13',false,'image/jpeg',decode('ffd8ff','hex')),
    ('asset-17-owner',17,'staff:botA','asset-17','pending-17',false,'image/jpeg',decode('ffd8ff','hex')),
    ('asset-20-pending-species',20,'staff:botA','asset-20','pending-20',false,'image/jpeg',decode('ffd8ff','hex'))`);
  await pool.query(`CREATE TABLE public.qr_code(
    qr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id INTEGER UNIQUE REFERENCES plant_record(plant_id),
    qr_code TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'generated'
  )`);

  const roles = { botA: "Botanist", botB: "Botanist", visitor: "Visitor", officer: "Conservation Officer" };
  const tokens = Object.fromEntries(Object.keys(roles).map((key, index) => [key, String(index + 1).repeat(64)]));
  const auth = {
    session: async (token) => {
      const key = Object.keys(tokens).find((candidate) => tokens[candidate] === token);
      return key ? { id: key, role: roles[key], status: "Active", mustChangePassword: false } : null;
    },
    event: async () => {},
  };
  const server = createPlantApp({ auth, pool, origins: new Set() }).listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(() => new Promise((resolve) => {
    server.closeAllConnections(); server.close(resolve);
  }));
  async function getPlants(account) {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api/plants`, {
      headers: { Authorization: `Bearer ${tokens[account]}` },
    });
    return (await response.json()).plants.filter((plant) => String(plant.species_id) === "6");
  }

  const botA = await getPlants("botA");
  const botB = await getPlants("botB");
  const visitor = await getPlants("visitor");
  const guest = await fetch(`http://127.0.0.1:${server.address().port}/api/plants`)
    .then((response) => response.json())
    .then((payload) => payload.plants.filter((plant) => String(plant.species_id) === "6"));
  const officer = await getPlants("officer");
  assert.deepEqual(botA.map((plant) => String(plant.plant_id)).sort(), ["11", "13", "17", "8"]);
  assert.deepEqual(botB.map((plant) => String(plant.plant_id)).sort(), ["14", "15", "8"]);
  assert.deepEqual(visitor.map((plant) => String(plant.plant_id)), ["8"]);
  assert.deepEqual(guest.map((plant) => String(plant.plant_id)), visitor.map((plant) => String(plant.plant_id)),
    "Guest and Visitor public plant discovery return the same approved public records");
  assert.ok(officer.some((plant) => String(plant.plant_id) === "18"));
  assert.ok(officer.some((plant) => String(plant.plant_id) === "19"));
  assert.equal(new Set(botA.map((plant) => String(plant.plant_id))).size, botA.length);
  assert.equal(botA.find((plant) => String(plant.plant_id) === "8").latest_approved.heightCm, 10);
  assert.equal(botA.find((plant) => String(plant.plant_id) === "8").latest_approved.lifeStage, "Mature");
  assert.equal(botA.find((plant) => String(plant.plant_id) === "8").plant_image_asset_id, "asset-8-current");
  assert.equal(botA.find((plant) => String(plant.plant_id) === "11").plant_image_asset_id, null);
  assert.equal(botA.find((plant) => String(plant.plant_id) === "13").plant_image_asset_id, "asset-13-owner");
  assert.equal(botA.find((plant) => String(plant.plant_id) === "13").zone, null,
    "the general catalogue exposes only approved plant location projections");
  const ownerPlantList = await fetch(`http://127.0.0.1:${server.address().port}/api/plants?scope=mine`, {
    headers: { Authorization: `Bearer ${tokens.botA}` },
  }).then((response) => response.json());
  assert.equal(ownerPlantList.plants.find((plant) => String(plant.plant_id) === "13").zone, "Zone B",
    "the owner-scoped list includes the submitted Zone even without approved coordinates");
  assert.equal(ownerPlantList.plants.some((plant) => String(plant.plant_id) === "14"), false);
  assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/api/plants?scope=mine`, {
    headers: { Authorization: `Bearer ${tokens.visitor}` },
  })).status, 403, "Visitors cannot use the owner-scoped pending projection");
  assert.equal(botA.find((plant) => String(plant.plant_id) === "17").plant_image_asset_id, "asset-17-owner");
  assert.equal(visitor[0].plant_image_asset_id, "asset-8-current");
  assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/api/plants/11`, {
    headers: { Authorization: `Bearer ${tokens.botB}` },
  })).status, 404, "another Botanist cannot open the owner's pending plant by ID");
  assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/api/plants/11`, {
    headers: { Authorization: `Bearer ${tokens.botA}` },
  })).status, 200, "the owner can open their pending plant detail");
  const ownPendingDetail = await fetch(`http://127.0.0.1:${server.address().port}/api/plants/13?scope=mine`, {
    headers: { Authorization: `Bearer ${tokens.botA}` },
  }).then((response) => response.json());
  assert.equal(ownPendingDetail.plant.latitude, 11.1);
  assert.equal(ownPendingDetail.plant.longitude, 22.2);
  assert.equal(ownPendingDetail.plant.accuracy_m, 5);
  assert.equal(ownPendingDetail.plant.altitude_m, 30);
  assert.equal(ownPendingDetail.plant.zone, "Zone B");
  assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/api/plants/13?scope=mine`, {
    headers: { Authorization: `Bearer ${tokens.botB}` },
  })).status, 404, "the owner-scoped GPS view cannot be used by another Botanist");
  assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/api/plants/11`, {
    headers: { Authorization: `Bearer ${tokens.visitor}` },
  })).status, 404, "Visitors cannot open a pending plant by ID");
  const pendingSpeciesDetailResponse = await fetch(`http://127.0.0.1:${server.address().port}/api/plants/20?scope=mine`, {
    headers: { Authorization: `Bearer ${tokens.botA}` },
  });
  const pendingSpeciesDetail = (await pendingSpeciesDetailResponse.json()).plant;
  assert.equal(pendingSpeciesDetailResponse.status, 200);
  assert.equal(pendingSpeciesDetail.species_details.scientific_name, "Owner Pending Species");
  assert.equal(pendingSpeciesDetail.species_details.common_name, "Owner pending common name");
  assert.equal(pendingSpeciesDetail.species_details.genus_name, null);
  assert.equal(pendingSpeciesDetail.latest_submission.notes, "Submitted plant notes");
  assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/api/plants/20?scope=mine`, {
    headers: { Authorization: `Bearer ${tokens.botB}` },
  })).status, 404, "another Botanist cannot use the owner-scoped species detail projection");
  assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/api/plants/20`, {
    headers: { Authorization: `Bearer ${tokens.visitor}` },
  })).status, 404, "Visitors cannot read an owner-scoped pending species detail");
  assert.deepEqual((await getPlantPhotos("botA", 20, "&scope=mine")).map((asset) => asset.id), ["asset-20-pending-species"]);
  assert.deepEqual(await getPlantPhotos("botB", 20, "&scope=mine"), []);
  assert.deepEqual(await getPlantPhotos("visitor", 20, "&scope=mine"), []);
  assert.equal((await getAsset("botA", "asset-20-pending-species", "?scope=mine")).status, 200);
  assert.equal((await getAsset("botB", "asset-20-pending-species", "?scope=mine")).status, 404);
  assert.equal((await getAsset("visitor", "asset-20-pending-species", "?scope=mine")).status, 404);
  for (const id of [18, 19]) {
    assert.equal(botA.some((plant) => String(plant.plant_id) === String(id)), false,
      "rejected and correction-required records stay out of the general Plants catalog");
    assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/api/plants/${id}`, {
      headers: { Authorization: `Bearer ${tokens.botA}` },
    })).status, 404, "rejected and correction-required records remain in owner-scoped submissions, not the catalog");
    assert.equal((await fetch(`http://127.0.0.1:${server.address().port}/api/plants/${id}?scope=mine`, {
      headers: { Authorization: `Bearer ${tokens.botA}` },
    })).status, 200, "the owner can still reach those records through the scoped submissions route");
  }
  async function getPlantPhotos(account, plantId, scope = "") {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api/assets?plant_id=${plantId}${scope}`, {
      headers: { Authorization: `Bearer ${tokens[account]}` },
    });
    return (await response.json()).assets;
  }
  assert.deepEqual(await getPlantPhotos("botA", 11, "&scope=mine"), []);
  assert.deepEqual(await getPlantPhotos("visitor", 11, "&scope=mine"), []);
  assert.deepEqual((await getPlantPhotos("visitor", 8)).map((asset) => asset.id), ["asset-8-current"]);
  async function getAsset(account, assetId, scope = "") {
    return fetch(`http://127.0.0.1:${server.address().port}/api/assets/${assetId}${scope}`, {
      headers: { Authorization: `Bearer ${tokens[account]}` },
    });
  }
  assert.equal((await getAsset("visitor", "asset-8-current")).status, 200);
  assert.equal((await getAsset("visitor", "asset-8-approved")).status, 404);
  assert.equal((await getAsset("botA", "asset-13-owner", "?scope=mine")).status, 200);
  assert.equal((await getAsset("botA", "asset-11-owner", "?scope=mine")).status, 404);
});
