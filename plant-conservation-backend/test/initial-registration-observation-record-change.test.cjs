test("failed canonical approval rolls back review evidence, Plant history, and photo changes", async t => {
  const { pool, plantId, initialId } = await fixture(t);
  const change = await submitInitialObservationEdit(pool, { user: owner, plantId, observationId: initialId,
    clientKey: "approval-rollback", ...proposal(32) });
  await pool.query(`CREATE FUNCTION plant_app.fail_initial_observation_update() RETURNS trigger
    LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'forced isolated rollback'; END $$;
    CREATE TRIGGER fail_initial_observation_update BEFORE UPDATE ON plant_app.plant_observation
      FOR EACH ROW WHEN (OLD.id='initial-observation') EXECUTE FUNCTION plant_app.fail_initial_observation_update()`);
  await assert.rejects(() => reviewInitialObservationEdit(pool, { user: officer, changeId: change.id,
    revision: 1, decision: "Approved", comment: "Verified" }), /forced isolated rollback/);
  assert.equal((await pool.query("SELECT status FROM record_change_submission WHERE id=$1", [change.id])).rows[0].status, "Pending Review");
  assert.equal((await pool.query("SELECT status FROM record_version_history WHERE change_id=$1", [change.id])).rows[0].status, "Pending Review");
  assert.equal((await pool.query("SELECT status FROM record_version_history WHERE id='plant-base-v1'")).rows[0].status, "Approved");
  assert.equal((await pool.query("SELECT count(*)::int AS n FROM record_change_review_event WHERE change_id=$1", [change.id])).rows[0].n, 0);
  assert.equal((await pool.query("SELECT count(*)::int AS n FROM plant_location WHERE plant_id=$1", [plantId])).rows[0].n, 1);
  assert.equal((await pool.query("SELECT status FROM plant_observation WHERE id=$1", [initialId])).rows[0].status, "Approved");
});

