test("Rejected and Correction Required preserve approved content; correction revisions remain immutable and cancellable", async t => {
  const { pool, plantId, initialId, originalContent } = await fixture(t);
  const correctionPhoto = await image("gold");
  const rejected = await submitInitialObservationEdit(pool, { user: owner, plantId, observationId: initialId,
    clientKey: "obs-edit-reject", ...proposal(22) });
  await reviewInitialObservationEdit(pool, { user: officer, changeId: rejected.id, revision: 1, decision: "Rejected", comment: "No" });
  assert.deepEqual((await pool.query("SELECT content FROM plant_observation WHERE id=$1", [initialId])).rows[0].content, originalContent);
  const correction = await submitInitialObservationEdit(pool, { user: owner, plantId, observationId: initialId,
    clientKey: "obs-edit-correct", ...proposal(23), photo_ids: ["initial-photo"],
    photos: [{ content_type: "image/jpeg", base64: correctionPhoto.toString("base64") }] });
  const firstVersion = (await pool.query("SELECT id,snapshot FROM record_version_history WHERE change_id=$1", [correction.id])).rows[0];
  const firstLinks = (await pool.query("SELECT position,asset_id FROM plant_record_version_photo WHERE version_id=$1 ORDER BY position", [firstVersion.id])).rows;
  const firstBytes = (await pool.query("SELECT asset_id,encode(content,'hex') AS bytes FROM plant_record_version_photo p JOIN plant_asset a ON a.id=p.asset_id WHERE p.version_id=$1 ORDER BY position", [firstVersion.id])).rows;
  assert.deepEqual(firstLinks.map(row => [row.position, row.asset_id]), [[0, "initial-photo"], [1, firstVersion.snapshot.photo_ids[1]]]);
  await reviewInitialObservationEdit(pool, { user: officer, changeId: correction.id, revision: 1,
    decision: "Correction Required", comment: "Clarify height" });
  assert.deepEqual((await pool.query("SELECT content FROM plant_observation WHERE id=$1", [initialId])).rows[0].content, originalContent);
  const resubmitted = await resubmitInitialObservationEdit(pool, { user: owner, changeId: correction.id, revision: 1,
    ...proposal(24) });
  assert.equal(resubmitted.revision, 2);
  let versions = (await pool.query("SELECT version_number,status,snapshot FROM record_version_history WHERE change_id=$1 ORDER BY version_number", [correction.id])).rows;
  assert.deepEqual(versions.map(row => row.status), ["Superseded", "Pending Review"]);
  assert.equal(versions[0].snapshot.content.heightCm, 23);
  await assert.rejects(() => cancelInitialObservationEdit(pool, { user: owner, changeId: correction.id }), /eligible initial Observation edit/);
  await reviewInitialObservationEdit(pool, { user: officer, changeId: correction.id, revision: 2,
    decision: "Correction Required", comment: "One more change" });
  const final = await resubmitInitialObservationEdit(pool, { user: owner, changeId: correction.id, revision: 2,
    ...proposal(26) });
  assert.equal(final.revision, 3);
  versions = (await pool.query("SELECT status,snapshot FROM record_version_history WHERE change_id=$1 ORDER BY version_number", [correction.id])).rows;
  assert.deepEqual(versions.map(row => row.status), ["Superseded", "Superseded", "Pending Review"]);
  assert.equal(versions[1].snapshot.content.heightCm, 24);
  await reviewInitialObservationEdit(pool, { user: officer, changeId: correction.id, revision: 3, decision: "Approved", comment: "Done" });
  assert.equal((await pool.query("SELECT content->>'heightCm' AS height FROM plant_observation WHERE id=$1", [initialId])).rows[0].height, "26");
  assert.deepEqual((await pool.query("SELECT asset_id,encode(content,'hex') AS bytes FROM plant_record_version_photo p JOIN plant_asset a ON a.id=p.asset_id WHERE p.version_id=$1 ORDER BY position", [firstVersion.id])).rows, firstBytes);
});

