test("local QR-only migration refuses a non-default index collation", async (t) => {
  const database = await testPool();
  t.after(() => database.end());
  await createLegacyQrTable(database);
  const alternateCollation = (await database.query(`
    SELECT alternate.collname
    FROM pg_collation alternate
    JOIN pg_attribute column_row
      ON column_row.attrelid = 'public.qr_code'::regclass
     AND column_row.attname = 'qr_code'
    WHERE alternate.oid <> column_row.attcollation
      AND alternate.collencoding IN (-1, 6)
    ORDER BY alternate.collname
    LIMIT 1
  `)).rows[0];
  if (!alternateCollation) {
    t.skip("PGlite exposes no alternate text collation for this test");
    return;
  }
  const collationName = `"${alternateCollation.collname.replace(/"/g, '""')}"`;
  await database.query(`
    ALTER TABLE public.qr_code DROP CONSTRAINT qr_code_qr_code_key;
    CREATE UNIQUE INDEX qr_code_qr_code_key
      ON public.qr_code(qr_code COLLATE ${collationName})
  `);

  await assert.rejects(
    applyMigration(database),
    /public\.qr_code indexes do not match the reviewed local index inventory/,
  );
  assert.equal((await database.query(
    "SELECT to_regclass('public.qr_code') IS NOT NULL AS source_remains",
  )).rows[0].source_remains, true);
  assert.equal((await database.query(
    "SELECT to_regclass('plant_app.qr_code') IS NULL AS destination_absent",
  )).rows[0].destination_absent, true);
});

