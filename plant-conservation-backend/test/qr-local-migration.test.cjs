async function assertQrMigrationRejectedForSetup(t, setup, message) {
  const database = await testPool();
  t.after(() => database.end());
  await createLegacyQrTable(database);
  await database.query(setup);

  await assert.rejects(applyMigration(database), message);
  assert.equal((await database.query(
    "SELECT to_regclass('public.qr_code') IS NOT NULL AS source_remains",
  )).rows[0].source_remains, true);
  assert.equal((await database.query(
    "SELECT to_regclass('plant_app.qr_code') IS NULL AS destination_absent",
  )).rows[0].destination_absent, true);
}

test("local QR-only migration preserves table data, identity, indexes, ACL, and plant_app FK", async (t) => {
  const database = await testPool();
  t.after(() => database.end());
  await createLegacyQrTable(database);
  await database.query("GRANT SELECT ON public.qr_code TO PUBLIC");
  const sequenceName = (await database.query(
    "SELECT pg_get_serial_sequence('public.qr_code', 'qr_id') AS name",
  )).rows[0].name;
  await database.query(`GRANT USAGE, SELECT ON SEQUENCE ${sequenceName} TO PUBLIC`);

  const before = (await database.query(`
    SELECT table_row.relowner::text AS owner, table_row.relacl::text AS acl,
      pg_get_serial_sequence('public.qr_code', 'qr_id') AS identity_sequence,
      sequence_row.relowner::text AS sequence_owner,
      sequence_row.relacl::text AS sequence_acl,
      EXISTS (
        SELECT 1 FROM pg_depend dependency
        WHERE dependency.classid = 'pg_class'::regclass
          AND dependency.objid = sequence_row.oid
          AND dependency.refclassid = 'pg_class'::regclass
          AND dependency.refobjid = table_row.oid
          AND dependency.refobjsubid = (
            SELECT attnum FROM pg_attribute
            WHERE attrelid = table_row.oid AND attname = 'qr_id'
          )
          AND dependency.deptype = 'i'
      ) AS identity_owned
    FROM pg_class table_row
    JOIN pg_class sequence_row
      ON sequence_row.oid = to_regclass(pg_get_serial_sequence('public.qr_code', 'qr_id'))
    WHERE table_row.oid = 'public.qr_code'::regclass
  `)).rows[0];
  const beforeIndexes = (await database.query(`
    SELECT indexname FROM pg_indexes
    WHERE schemaname = 'public' AND tablename = 'qr_code'
    ORDER BY indexname
  `)).rows.map((row) => row.indexname);
  assert.deepEqual(beforeIndexes, [
    "qr_code_pkey",
    "qr_code_plant_id_key",
    "qr_code_qr_code_key",
  ]);
  const beforeRows = (await database.query(`
    SELECT qr_id, plant_id, qr_code, status, assigned_at
    FROM public.qr_code
  `)).rows;
  const beforeScanHistoryRows = (await database.query(`
    SELECT scan_id, qr_id FROM public.qr_scan_history ORDER BY scan_id
  `)).rows;
  const beforeStatus = (await database.query(`
    SELECT format_type(column_row.atttypid, column_row.atttypmod) AS status_type,
      pg_get_expr(default_row.adbin, default_row.adrelid) AS status_default
    FROM pg_attribute column_row
    JOIN pg_attrdef default_row
      ON default_row.adrelid = column_row.attrelid
     AND default_row.adnum = column_row.attnum
    WHERE column_row.attrelid = 'public.qr_code'::regclass
      AND column_row.attname = 'status'
  `)).rows[0];
  assert.equal(beforeStatus.status_type, "character varying(30)");
  assert.equal(beforeStatus.status_default, "'generated'::character varying");
  const beforePlantColumns = (await database.query(`
    SELECT attname, format_type(atttypid, atttypmod) AS column_type, attnotnull
    FROM pg_attribute
    WHERE attrelid = 'public.plant_record'::regclass
      AND attnum > 0 AND NOT attisdropped
    ORDER BY attnum
  `)).rows;
  const beforePlantRows = (await database.query(`
    SELECT plant_id, species_id, registered_by, registered_at, current_status,
      created_at, updated_at
    FROM public.plant_record
  `)).rows;
  const beforeAppPlantRows = (await database.query(`
    SELECT plant_id, species_id, registered_subject, rbac_status, qr_token
    FROM plant_app.plant_record
  `)).rows;
  assert.deepEqual(beforePlantColumns, [
    { attname: "plant_id", column_type: "bigint", attnotnull: true },
    { attname: "species_id", column_type: "bigint", attnotnull: true },
    { attname: "registered_by", column_type: "bigint", attnotnull: true },
    { attname: "registered_at", column_type: "timestamp with time zone", attnotnull: true },
    { attname: "current_status", column_type: "character varying", attnotnull: true },
    { attname: "created_at", column_type: "timestamp with time zone", attnotnull: true },
    { attname: "updated_at", column_type: "timestamp with time zone", attnotnull: true },
  ]);

  await applyMigration(database);

  const after = (await database.query(`
    SELECT table_row.relowner::text AS owner, table_row.relacl::text AS acl,
      pg_get_serial_sequence('plant_app.qr_code', 'qr_id') AS identity_sequence,
      sequence_row.relowner::text AS sequence_owner,
      sequence_row.relacl::text AS sequence_acl,
      EXISTS (
        SELECT 1 FROM pg_depend dependency
        WHERE dependency.classid = 'pg_class'::regclass
          AND dependency.objid = sequence_row.oid
          AND dependency.refclassid = 'pg_class'::regclass
          AND dependency.refobjid = table_row.oid
          AND dependency.refobjsubid = (
            SELECT attnum FROM pg_attribute
            WHERE attrelid = table_row.oid AND attname = 'qr_id'
          )
          AND dependency.deptype = 'i'
      ) AS identity_owned
    FROM pg_class table_row
    JOIN pg_class sequence_row
      ON sequence_row.oid = to_regclass(pg_get_serial_sequence('plant_app.qr_code', 'qr_id'))
    WHERE table_row.oid = 'plant_app.qr_code'::regclass
  `)).rows[0];
  const afterIndexes = (await database.query(`
    SELECT indexname FROM pg_indexes
    WHERE schemaname = 'plant_app' AND tablename = 'qr_code'
    ORDER BY indexname
  `)).rows.map((row) => row.indexname);
  const foreignKey = (await database.query(`
    SELECT parent_namespace.nspname AS parent_schema,
      parent_table.relname AS parent_table,
      constraint_row.confdeltype AS delete_action,
      constraint_row.convalidated AS validated
    FROM pg_constraint constraint_row
    JOIN pg_class source_table ON source_table.oid = constraint_row.conrelid
    JOIN pg_class parent_table ON parent_table.oid = constraint_row.confrelid
    JOIN pg_namespace parent_namespace ON parent_namespace.oid = parent_table.relnamespace
    WHERE source_table.oid = 'plant_app.qr_code'::regclass
      AND constraint_row.conname = 'qr_code_plant_id_fkey'
  `)).rows[0];
  const incomingForeignKey = (await database.query(`
    SELECT constraint_row.confrelid = 'plant_app.qr_code'::regclass AS preserved,
      (SELECT attname FROM pg_attribute
       WHERE attrelid = constraint_row.conrelid
         AND attnum = constraint_row.conkey[1]) AS referencing_column,
      (SELECT attname FROM pg_attribute
       WHERE attrelid = constraint_row.confrelid
         AND attnum = constraint_row.confkey[1]) AS referenced_column,
      constraint_row.confdeltype AS delete_action,
      constraint_row.confupdtype AS update_action,
      constraint_row.confmatchtype AS match_type,
      constraint_row.condeferrable AS deferrable,
      constraint_row.condeferred AS initially_deferred,
      constraint_row.convalidated AS validated
    FROM pg_constraint constraint_row
    WHERE constraint_row.conrelid = 'public.qr_scan_history'::regclass
      AND constraint_row.conname = 'qr_scan_history_qr_id_fkey'
  `)).rows[0];

  assert.equal((await database.query(
    "SELECT to_regclass('public.qr_code') IS NULL AS moved",
  )).rows[0].moved, true);
  assert.equal((await database.query(
    "SELECT to_regclass('plant_app.plant_record') IS NOT NULL AS app_plant_preserved",
  )).rows[0].app_plant_preserved, true);
  assert.deepEqual((await database.query(`
    SELECT attname, format_type(atttypid, atttypmod) AS column_type, attnotnull
    FROM pg_attribute
    WHERE attrelid = 'public.plant_record'::regclass
      AND attnum > 0 AND NOT attisdropped
    ORDER BY attnum
  `)).rows, beforePlantColumns);
  assert.deepEqual(
    (await database.query(`
      SELECT plant_id, species_id, registered_by, registered_at, current_status,
        created_at, updated_at
      FROM public.plant_record
    `)).rows,
    beforePlantRows,
  );
  assert.deepEqual(
    (await database.query(`
      SELECT plant_id, species_id, registered_subject, rbac_status, qr_token
      FROM plant_app.plant_record
    `)).rows,
    beforeAppPlantRows,
  );
  assert.deepEqual(
    (await database.query(`
      SELECT qr_id, plant_id, qr_code, status, assigned_at
      FROM plant_app.qr_code
    `)).rows,
    beforeRows,
  );
  assert.deepEqual(
    (await database.query(`
      SELECT scan_id, qr_id FROM public.qr_scan_history ORDER BY scan_id
    `)).rows,
    beforeScanHistoryRows,
  );
  assert.equal(after.owner, before.owner);
  assert.equal(after.acl, before.acl);
  assert.notEqual(after.acl, null);
  assert.equal(after.sequence_owner, before.sequence_owner);
  assert.equal(after.sequence_acl, before.sequence_acl);
  assert.notEqual(after.sequence_acl, null);
  assert.equal(before.identity_owned, true);
  assert.equal(after.identity_owned, true);
  assert.deepEqual(afterIndexes, beforeIndexes);
  const afterStatus = (await database.query(`
    SELECT format_type(column_row.atttypid, column_row.atttypmod) AS status_type,
      pg_get_expr(default_row.adbin, default_row.adrelid) AS status_default
    FROM pg_attribute column_row
    JOIN pg_attrdef default_row
      ON default_row.adrelid = column_row.attrelid
     AND default_row.adnum = column_row.attnum
    WHERE column_row.attrelid = 'plant_app.qr_code'::regclass
      AND column_row.attname = 'status'
  `)).rows[0];
  assert.deepEqual(afterStatus, beforeStatus);
  assert.equal(foreignKey.parent_schema, "plant_app");
  assert.equal(foreignKey.parent_table, "plant_record");
  assert.equal(foreignKey.delete_action, "n");
  assert.equal(foreignKey.validated, true);
  assert.equal(incomingForeignKey.preserved, true);
  assert.equal(incomingForeignKey.referencing_column, "qr_id");
  assert.equal(incomingForeignKey.referenced_column, "qr_id");
  assert.equal(incomingForeignKey.delete_action, "c");
  assert.equal(incomingForeignKey.update_action, "a");
  assert.equal(incomingForeignKey.match_type, "s");
  assert.equal(incomingForeignKey.deferrable, false);
  assert.equal(incomingForeignKey.initially_deferred, false);
  assert.equal(incomingForeignKey.validated, true);
  assert.notEqual(after.identity_sequence, before.identity_sequence);
  assert.match(after.identity_sequence, /^plant_app\./);

  const next = (await database.query(`
    INSERT INTO plant_app.qr_code(qr_code)
    VALUES ('generated-after-move')
    RETURNING qr_id
  `)).rows[0].qr_id;
  assert.ok(BigInt(next) > BigInt(beforeRows[0].qr_id));
});

