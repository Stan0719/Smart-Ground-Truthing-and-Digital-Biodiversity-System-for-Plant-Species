"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { once } = require("node:events");
const { createPlantDatabase } = require("./postgres-fixture.cjs");
const { createPlantApp } = require("../server.js");

test("QR inventory deletion and assignment remain globally unique and authorized", async (t) => {
  const pool = await createPlantDatabase();
  t.after(() => pool.end());
  await pool.query(`CREATE TABLE public.qr_code(
    qr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id INTEGER UNIQUE REFERENCES plant_record(plant_id) ON DELETE SET NULL,
    qr_code TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'generated',
    generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    assigned_at TIMESTAMPTZ,
    activated_at TIMESTAMPTZ,
    retired_at TIMESTAMPTZ
  )`);
  await pool.query("INSERT INTO species(scientific_name) VALUES('QR test species'); INSERT INTO rbac_species_visibility VALUES(1,'public')");
  const assignedPlant = (await pool.query(
    "INSERT INTO plant_record(species_id,registered_subject,rbac_status,qr_token) VALUES(1,'staff:existing','Approved','assigned-token') RETURNING plant_id",
  )).rows[0].plant_id;
  await pool.query(
    "INSERT INTO public.qr_code(qr_id,plant_id,qr_code,status) VALUES(1,NULL,'delete-token','generated'),(2,$1,'assigned-token','assigned'),(3,NULL,'retired-token','retired'),(4,NULL,'sequential-token','generated'),(5,NULL,'concurrent-token','generated')",
    [assignedPlant],
  );

  const roles = { botA: "Botanist", botB: "Botanist", visitor: "Visitor" };
  const tokens = Object.fromEntries(Object.keys(roles).map((key, index) => [key, String(index + 1).repeat(64)]));
  const auth = {
    session: async (token) => {
      const key = Object.keys(tokens).find((candidate) => tokens[candidate] === token);
      return key ? { id: key, role: roles[key], status: "Active", mustChangePassword: false } : null;
    },
    event: async () => {},
  };
  const server = createPlantApp({ auth, pool, origins: new Set() }).listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(() => new Promise((resolve) => {
    server.closeAllConnections();
    server.close(resolve);
  }));
  const base = `http://127.0.0.1:${server.address().port}/api`;
  async function call(path, account, method = "GET", body) {
    const response = await fetch(base + path, {
      method,
      headers: {
        "Content-Type": "application/json",
        ...(tokens[account] ? { Authorization: `Bearer ${tokens[account]}` } : {}),
      },
      body: body === undefined && method !== "GET" ? JSON.stringify({}) : body === undefined ? undefined : JSON.stringify(body),
    });
    return { status: response.status, data: await response.json() };
  }

  await t.test("unused QR is globally available, deletable, and absent after inventory refresh", async () => {
    const firstAccount = await call("/qr-codes", "botA");
    const secondAccount = await call("/qr-codes", "botB");
    assert.equal(firstAccount.status, 200);
    assert.deepEqual(firstAccount.data.qr_codes, secondAccount.data.qr_codes);
    assert.ok(firstAccount.data.qr_codes.some((qr) => String(qr.qr_id) === "1" && qr.plant_id == null));
    assert.equal(firstAccount.data.qr_codes.find((qr) => String(qr.qr_id) === "3").status, "retired");

    assert.deepEqual(await call("/qr-codes/1", "botA", "DELETE"), {
      status: 200,
      data: { deleted: true, qr_id: "1" },
    });
    const refreshedA = await call("/qr-codes", "botA");
    const refreshedB = await call("/qr-codes", "botB");
    assert.ok(refreshedA.data.qr_codes.every((qr) => String(qr.qr_id) !== "1"));
    assert.deepEqual(refreshedA.data.qr_codes, refreshedB.data.qr_codes);
    assert.equal((await pool.query("SELECT count(*)::int AS count FROM public.qr_code WHERE qr_id=1")).rows[0].count, 0);
  });

  await t.test("assigned and retired QR records cannot be deleted", async () => {
    assert.equal((await call("/qr-codes/2", "botA", "DELETE")).status, 409);
    assert.equal((await call("/qr-codes/3", "botA", "DELETE")).status, 409);
    assert.equal((await pool.query("SELECT count(*)::int AS count FROM public.qr_code WHERE qr_id IN (2,3)")).rows[0].count, 2);
  });

  const plantRequest = (qrId, key, scientificName) => ({
    species_id: 1,
    scientific_name: scientificName,
    qr_id: qrId,
    latitude: 4.5,
    longitude: 113.7,
    client_key: key,
    content: { heightCm: 12, healthStatus: "Healthy", lifeStage: "Mature", morphology: "Observed" },
  });
  await t.test("a QR cannot be assigned to a second plant, including concurrent requests", async () => {
    const first = await call("/plants", "botA", "POST", plantRequest(4, "sequential-a", "Plant A"));
    assert.equal(first.status, 201);
    const second = await call("/plants", "botB", "POST", plantRequest(4, "sequential-b", "Plant B"));
    assert.equal(second.status, 409);
    const visibleToOtherBotanist = await call("/qr-codes", "botB");
    const sharedQr = visibleToOtherBotanist.data.qr_codes.find((qr) => String(qr.qr_id) === "4");
    assert.ok(sharedQr.plant_id != null);
    assert.equal(sharedQr.status, "assigned");
    const concurrent = await Promise.all([
      call("/plants", "botA", "POST", plantRequest(5, "concurrent-a", "Plant C")),
      call("/plants", "botB", "POST", plantRequest(5, "concurrent-b", "Plant D")),
    ]);
    assert.deepEqual(concurrent.map((result) => result.status).sort(), [201, 409]);
    const qrRows = (await pool.query("SELECT qr_id,plant_id,qr_code,status FROM public.qr_code WHERE qr_id IN (4,5) ORDER BY qr_id")).rows;
    assert.equal(qrRows.length, 2);
    assert.ok(qrRows.every((qr) => qr.plant_id != null && qr.status === "assigned"));
    assert.equal((await pool.query("SELECT count(*)::int AS count FROM plant_record WHERE qr_token IN ('sequential-token','concurrent-token')")).rows[0].count, 2);
    assert.equal((await call("/qr-codes/4", "botA", "DELETE")).status, 409);
  });

  await t.test("inventory and delete enforce Botanist authentication and role", async () => {
    assert.equal((await call("/qr-codes", null)).status, 401);
    assert.equal((await call("/qr-codes", "visitor")).status, 403);
    assert.equal((await call("/qr-codes/4", null, "DELETE")).status, 403);
    assert.equal((await call("/qr-codes/4", "visitor", "DELETE")).status, 403);
    assert.equal((await call("/qr-codes/999", "botA", "DELETE")).status, 404);
  });
});
