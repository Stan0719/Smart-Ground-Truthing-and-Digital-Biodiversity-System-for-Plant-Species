"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { once } = require("node:events");
const { createPlantDatabase } = require("./postgres-fixture.cjs");
const { createPlantApp } = require("../server.js");

test("QR lookup resolves only approved, visible plant assignments", async (t) => {
  const pool = await createPlantDatabase();
  t.after(() => pool.end());
  await pool.query(`CREATE TABLE public.qr_code(
    qr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id INTEGER UNIQUE REFERENCES plant_record(plant_id) ON DELETE SET NULL,
    qr_code TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'generated'
  )`);
  await pool.query("INSERT INTO species(scientific_name) VALUES('Public'),('Protected')");
  await pool.query("INSERT INTO rbac_species_visibility VALUES(1,'public'),(2,'protected')");
  await pool.query(`INSERT INTO plant_record(plant_id,species_id,registered_subject,rbac_status,qr_token,scientific_name)
    VALUES(1,1,'staff:bot','Approved','payload-approved','Public plant'),
          (2,1,'staff:bot','Pending Review','payload-pending','Pending plant'),
          (3,2,'staff:bot','Approved','payload-protected','Protected plant')`);
  await pool.query(`INSERT INTO public.qr_code(qr_id,plant_id,qr_code,status)
    VALUES(8,1,'payload-approved','assigned'),(9,2,'payload-pending','assigned'),
          (10,3,'payload-protected','assigned'),(11,NULL,'payload-unused','generated'),
          (12,NULL,'payload-retired','retired')`);

  const roles = { botanist: "Botanist", visitor: "Visitor" };
  const tokens = Object.fromEntries(Object.keys(roles).map((key, index) => [key, String(index + 1).repeat(64)]));
  const auth = {
    session: async (token) => {
      const key = Object.keys(tokens).find((candidate) => tokens[candidate] === token);
      return key ? { id: key, role: roles[key], status: "Active", mustChangePassword: false } : null;
    },
    event: async () => {},
  };
  const server = createPlantApp({ auth, pool, origins: new Set() }).listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(() => new Promise((resolve) => {
    server.closeAllConnections(); server.close(resolve);
  }));
  async function call(token, payload) {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api/qr/${encodeURIComponent(payload)}`, {
      headers: token ? { Authorization: `Bearer ${tokens[token]}` } : {},
    });
    return { status: response.status, data: await response.json() };
  }

  await t.test("assigned QR resolves the exact plant through its stored payload", async () => {
    const resolved = await call("botanist", "payload-approved");
    assert.equal(resolved.status, 200);
    assert.equal(resolved.data.assigned, true);
    assert.equal(resolved.data.plant.plant_id, 1);
    assert.equal(resolved.data.plant.scientific_name, "Public plant");
  });
  await t.test("unused and retired QR codes are never resolved as plants", async () => {
    assert.deepEqual(await call("botanist", "payload-unused"), { status: 200, data: { assigned: false } });
    assert.deepEqual(await call("botanist", "payload-retired"), { status: 200, data: { assigned: false } });
  });
  await t.test("pending and protected plant information is not disclosed", async () => {
    assert.equal((await call("botanist", "payload-pending")).status, 404);
    assert.equal((await call("visitor", "payload-pending")).status, 404);
    assert.equal((await call("visitor", "payload-protected")).status, 404);
    assert.equal((await call("botanist", "payload-protected")).status, 404);
  });
  await t.test("invalid tokens and anonymous public lookup obey visibility", async () => {
    assert.equal((await call("botanist", "does-not-exist")).status, 404);
    // QR scans are intentionally public for public-approved plants.
    assert.equal((await call(null, "payload-approved")).status, 200);
    assert.equal((await call(null, "payload-protected")).status, 404);
  });
});
