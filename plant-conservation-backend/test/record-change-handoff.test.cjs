"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { readFileSync } = require("node:fs");
const { join } = require("node:path");
const { once } = require("node:events");
const sharp = require("sharp");
const { createPlantDatabase, installRecordChangeNotifications, installTranslationStorage } = require("./postgres-fixture.cjs");
const { createOfficerNotificationDelivery } = require("../officer-notification-delivery.cjs");
const { createPlantApp } = require("../server.js");

test("approved-record handoff: queue, transactional outbox, recipients and competing decisions", async (t) => {
  const pool = await createPlantDatabase();
  await pool.query("CREATE SCHEMA IF NOT EXISTS plant_app; SET search_path=plant_app,pg_catalog");
  await pool.query(readFileSync(join(__dirname, "../schema.postgres.sql"), "utf8"));
  t.after(() => pool.end());
  const migration = (name) => readFileSync(join(__dirname, `../migrations/${name}`), "utf8");
  await pool.query(migration("004-species-requests.sql"));
  await pool.query(migration("006-atomic-plant-submissions.sql"));
  await pool.query(migration("016-species-request-content-revision.sql"));
  await pool.query(migration("017-species-review-cycle.sql"));
  // This isolated test schema is disposable. No production migration is run.
  await pool.query(migration("008-record-change-submissions.sql"));
  await pool.query(migration("009-record-version-history.sql"));
  await installRecordChangeNotifications(pool);
  await installTranslationStorage(pool);
  const photo = await sharp({ create: { width: 4, height: 4, channels: 3, background: "green" } }).jpeg().toBuffer();
  const species = (await pool.query("INSERT INTO species(scientific_name,common_name,description,rbac_data) VALUES('Species A','Common A','Original description',$1) RETURNING species_id",
    [{ habitat: "Forest", culturalSignificance: "Existing cultural knowledge", retainedMetadata: { source: "fixture" }, approvalStatus: "Approved", submittedBy: "staff:bot" }])).rows[0].species_id;
  await pool.query("INSERT INTO rbac_species_visibility(species_id,visibility) VALUES($1,'public')", [species]);
  const request = (await pool.query(`INSERT INTO species_request_submission(owner_subject,client_key,payload_hash,scientific_name,common_name,genus_name,family_name,conservation_status,description,habitat,photo,request_status,approved_species_id)
    VALUES('staff:bot','species-key','hash','Species A','Common A','Genus A','Family A','Least Concern','Original description','Forest',$1,'Approved',$2) RETURNING request_id`,
    [photo, species])).rows[0].request_id;
  const approvedPlant = (await pool.query("INSERT INTO plant_record(species_id,registered_subject,scientific_name,rbac_status,qr_token) VALUES($1,'staff:bot','Plant A','Approved','qr-edit-approved') RETURNING plant_id", [species])).rows[0].plant_id;
  const pendingPlant = (await pool.query("INSERT INTO plant_record(species_id,registered_subject,scientific_name,rbac_status,qr_token) VALUES($1,'staff:bot','Plant Pending','Pending Review','qr-edit-pending') RETURNING plant_id", [species])).rows[0].plant_id;
  await pool.query(`CREATE TABLE plant_app.qr_code(qr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id INTEGER UNIQUE,qr_code TEXT UNIQUE NOT NULL,status TEXT NOT NULL,assigned_at TIMESTAMPTZ,activated_at TIMESTAMPTZ,retired_at TIMESTAMPTZ)`);
  await pool.query(`INSERT INTO plant_app.qr_code(plant_id,qr_code,status) VALUES($1,'qr-edit-approved','assigned'),($2,'qr-edit-pending','assigned'),(NULL,'qr-edit-free','generated'),(NULL,'qr-edit-free-two','generated')`,
  [approvedPlant, pendingPlant]);
  const content = { heightCm: 20, healthStatus: "Healthy", lifeStage: "Mature", morphology: "Original", taxonomy: "Existing taxonomy", latitude: 4.5, longitude: 113.7, altitudeM: 14, zone: "Original zone", notes: "" };
  await pool.query("INSERT INTO plant_observation(id,plant_id,owner_subject,status,content,client_key) VALUES('approved-observation',$1,'staff:bot','Approved',$2,'approved-obs-key'),('pending-observation',$3,'staff:bot','Pending Review',$2,'pending-obs-key')", [approvedPlant, content, pendingPlant]);
  await pool.query("INSERT INTO plant_asset(id,plant_id,owner_subject,client_key,observation_id,approved,content_type,content) VALUES('old-photo',$1,'staff:bot','old-photo-key','approved-observation',TRUE,'image/jpeg',$2)", [approvedPlant, photo]);
  // Explicit atomic-registration provenance for this approved fixture.
  await pool.query(`INSERT INTO plant_submission_receipt(owner_subject,client_key,payload_hash,result)
    SELECT o.owner_subject,o.client_key,$1,jsonb_build_object('id',o.id,'plant_id',p.plant_id,
      'species_id',p.species_id,'qr_token',p.qr_token,'status','Pending Review','species_request_id',NULL)
    FROM plant_observation o JOIN plant_record p ON p.plant_id=o.plant_id
    WHERE o.id='approved-observation'`, ['a'.repeat(64)]);
  const roles = { bot: "Botanist", other: "Botanist", officer: "Conservation Officer", officerTwo: "Conservation Officer" };
  const tokens = Object.fromEntries(Object.keys(roles).map((key, index) => [key, String(index + 1).repeat(64)]));
  const auth = { session: async (token) => {
    const account = Object.keys(tokens).find((key) => tokens[key] === token);
    return account ? { id: account, role: roles[account], status: "Active", mustChangePassword: false } : null;
  }, event: async () => {} };
  await pool.query(migration("013-staff-notification-foundation.sql"));
  auth.db = { prepare: () => ({ all: async () => [
    {id:'officer',role:'Conservation Officer',status:'Active',must_change_password:0},
    {id:'inactive',role:'Conservation Officer',status:'Inactive',must_change_password:0},
    {id:'temporary',role:'Conservation Officer',status:'Active',must_change_password:1},
    {id:'bot',role:'Botanist',status:'Active',must_change_password:0},
  ] }) };
  const delivery = createOfficerNotificationDelivery({pool,auth});
  const server = createPlantApp({ pool, auth, officerNotifications:delivery }).listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(async () => { server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); });
  const base = `http://127.0.0.1:${server.address().port}/api`;
  async function call(path, role = "bot", method = "GET", body) {
    if (path.startsWith('/my-species-requests/') && method === 'PATCH' && body && !Object.hasOwn(body, 'expected_revision')) {
      const current = (await pool.query('SELECT content_revision,review_cycle FROM species_request_submission WHERE request_id::text=$1', [path.split('/')[2]])).rows[0];
      body = { ...body, expected_revision: current?.content_revision };
    }
    if (/^\/species-requests\/\d+\/review$/.test(path) && body && !Object.hasOwn(body, 'expected_revision')) {
      const row = (await pool.query('SELECT content_revision,review_cycle FROM species_request_submission WHERE request_id::text=$1', [path.split('/')[2]])).rows[0];
      body = { ...body, expected_review_cycle: row?.review_cycle || 1, expected_revision: row?.content_revision || 1 };
    }

    const response = await fetch(base + path, { method, headers: { "Content-Type": "application/json", Authorization: `Bearer ${tokens[role]}` }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, data: await response.json() };
  }
  const plant = (name, latitude = content.latitude, longitude = content.longitude) => ({ species_id: species, scientific_name: name,
    content: { ...content, latitude, longitude, heightCm: 30, morphology: "Changed" } });
  const speciesData = (name) => ({ scientific_name: name, common_name: "Common B", genus_name: "Genus B", family_name: "Family B",
    conservation_status: "Near Threatened", description: "Updated description", habitat: "Wet forest" });


  const proposal = {kind:'plant',target_id:approvedPlant,proposed:plant('Proposed only'),client_key:'handoff'};
  const created = await call('/record-changes','bot','POST',proposal);
  assert.equal(created.status,201,JSON.stringify(created.data));
  const id=created.data.change.id;
  assert.equal((await call('/record-changes','bot','POST',proposal)).data.change.id,id);
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM staff_notification_event')).rows[0].n,1);
  assert.equal((await pool.query('SELECT scientific_name FROM plant_record WHERE plant_id=$1',[approvedPlant])).rows[0].scientific_name,'Plant A');
  const speciesProposal=await call('/record-changes','bot','POST',{kind:'species',target_id:request,proposed:speciesData('Proposed species'),client_key:'species-handoff'});
  assert.equal(speciesProposal.status,201,JSON.stringify(speciesProposal.data));
  const first=await call('/record-changes?limit=1&status=Pending%20Review','officer');
  assert.equal(first.data.changes.length,1);assert.equal(first.data.page.has_more,true);
  const second=await call('/record-changes?limit=1&cursor='+first.data.page.next_cursor,'officer');
  assert.equal(second.data.changes.length,1);assert.notEqual(second.data.changes[0].id,first.data.changes[0].id);
  assert.equal((await call('/record-changes?search=Proposed%20only','officer')).data.changes[0].id,id);
  assert.equal((await call('/record-changes/'+id,'other')).status,404);
  await delivery.deliverBatch();await delivery.deliverBatch();
  const recipients=(await pool.query('SELECT recipient_subject FROM staff_notification')).rows;
  assert.equal(recipients.length,2);assert.ok(recipients.every(r=>r.recipient_subject==='staff:officer'));
  const inbox=await call('/staff-notifications','officer');
  assert.equal(inbox.status,200);assert.equal(inbox.data.notifications.length,2);
  assert.deepEqual(new Set(inbox.data.notifications.map(n=>n.change_target_type)),new Set(['plant','species']));
  const decisions=await Promise.all(['Approved','Rejected'].map((decision,index)=>call('/record-changes/'+id+'/review',index?'officerTwo':'officer','POST',{decision,comment:'Checked'})));
  assert.deepEqual(decisions.map(r=>r.status).sort(),[200,409]);
  const speciesId=speciesProposal.data.change.id;
  await pool.query("UPDATE species SET description='Changed externally' WHERE species_id=$1",[species]);
  assert.equal((await call('/record-changes/'+speciesId+'/review','officer','POST',{decision:'Approved',comment:'Stale'})).status,409);
  assert.equal((await call('/record-changes/'+speciesId+'/review','officer','POST',{decision:'Rejected',comment:'Retain base'})).status,200);
  const own=await call('/record-changes','bot','POST',{...proposal,client_key:'owner-check'});
  assert.equal(own.status,201);
  await pool.query("UPDATE record_change_submission SET owner_subject='staff:officer' WHERE id=$1",[own.data.change.id]);
  assert.equal((await call('/record-changes/'+own.data.change.id+'/review','officer','POST',{decision:'Rejected',comment:'Self'})).status,403);
  await delivery.deliverBatch();
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM staff_notification')).rows[0].n,2,'owner receives no notification');
  assert.equal((await call('/record-changes/'+own.data.change.id+'/review','officerTwo','POST',{decision:'Rejected',comment:'Independent'})).status,200);
  // A new proposal cannot commit without notification storage. No live DB is used.
  await pool.query('ALTER TABLE staff_notification_event RENAME TO hidden_events');
  const before=(await pool.query('SELECT count(*)::int AS n FROM record_change_submission')).rows[0].n;
  const failed=await call('/record-changes','bot','POST',{...proposal,client_key:'missing-storage',proposed:plant('Must roll back')});
  assert.equal(failed.status,503,JSON.stringify(failed.data));
  assert.equal((await pool.query('SELECT count(*)::int AS n FROM record_change_submission')).rows[0].n,before);
});
