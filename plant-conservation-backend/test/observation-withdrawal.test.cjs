"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { readFileSync } = require("node:fs");
const { join } = require("node:path");
const { once } = require("node:events");
const { randomUUID } = require("node:crypto");
const { createPlantDatabase } = require("./postgres-fixture.cjs");
const { createPlantApp } = require("../server.js");

test("original field Observation withdrawal is owner-scoped, audited, non-destructive, and race-safe", async (t) => {
  const pool = await createPlantDatabase();
  t.after(() => pool.end());
  await pool.query("SET search_path TO plant_app,pg_catalog");
  const migrate = (name) => pool.query(readFileSync(join(__dirname, `../migrations/${name}.sql`), "utf8"));
  for (const name of ["004-species-requests", "006-atomic-plant-submissions", "008-record-change-submissions",
    "009-record-version-history", "021-observation-edit-requests", "022-cancel-edit-requests", "025-original-plant-withdrawal"])
    await migrate(name);
  await migrate("027-original-observation-withdrawal");
  await migrate("027-original-observation-withdrawal");
  await pool.query(`CREATE TABLE plant_app.qr_code(qr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id INTEGER UNIQUE,qr_code TEXT UNIQUE NOT NULL,status TEXT NOT NULL)`);
  const speciesId = (await pool.query(`INSERT INTO species(scientific_name,common_name,rbac_data)
    VALUES('Observation withdrawal species','Withdrawal species','{}') RETURNING species_id`)).rows[0].species_id;
  await pool.query("INSERT INTO rbac_species_visibility(species_id,visibility) VALUES($1,'public')", [speciesId]);
  let seq = 0;
  async function plant(status = "Approved") {
    const key = `obs-withdraw-${++seq}`;
    const result = (await pool.query(`INSERT INTO plant_record(species_id,registered_subject,scientific_name,rbac_status,qr_token)
      VALUES($1,'staff:alice',$2,$3,$2) RETURNING plant_id`, [speciesId, key, status])).rows[0];
    await pool.query("INSERT INTO plant_app.qr_code(plant_id,qr_code,status) VALUES($1,$2,'active')", [result.plant_id, key]);
    return result.plant_id;
  }
  async function observation(status, origin = "subsequent_observation", parentStatus = "Approved", id = randomUUID()) {
    const plantId = await plant(parentStatus);
    await pool.query(`INSERT INTO plant_observation(id,plant_id,owner_subject,status,content,client_key,origin_type)
      VALUES($1,$2,'staff:alice',$3,$4,$1,$5)`, [id, plantId, status,
      { heightCm: 80, healthStatus: "Healthy", lifeStage: "Mature", morphology: "Leaves", notes: "Preserve me" }, origin]);
    return { id, plantId };
  }
  const pending = await observation("Pending Review");
  const correction = await observation("Correction Required");
  const rejected = await observation("Rejected");
  const approved = await observation("Approved");
  const initial = await observation("Pending Review", "initial_registration");
  const blockedParent = await observation("Pending Review", "subsequent_observation", "Pending Review");
  const resubmitted = await observation("Pending Review");
  await pool.query(`INSERT INTO observation_review(id,observation_id,reviewer_subject,decision,comment)
    VALUES('correction-history',$1,'staff:officer','Correction Required','Keep this feedback')`, [correction.id]);
  await pool.query(`INSERT INTO observation_review(id,observation_id,reviewer_subject,decision,comment)
    VALUES('rejected-history',$1,'staff:officer','Rejected','Rejected feedback')`, [rejected.id]);
  await pool.query(`INSERT INTO observation_review(id,observation_id,reviewer_subject,decision,comment)
    VALUES('resubmission-history',$1,'staff:officer','Correction Required','Resubmission is locked')`, [resubmitted.id]);
  await pool.query(`INSERT INTO observation_edit_request(id,observation_id,owner_subject,version_number,base_revision,
    base_fingerprint,base_snapshot,proposed_content,client_key,payload_hash)
    VALUES('active-edit',$1,'staff:alice',1,1,'fingerprint','{}','{}','active-edit-key','hash')`, [pending.id]);
  const photo = Buffer.from([1, 2, 3]);
  await pool.query(`INSERT INTO plant_asset(id,plant_id,owner_subject,client_key,observation_id,approved,content_type,content)
    VALUES('observation-photo',$1,'staff:alice','photo-key',$2,FALSE,'image/jpeg',$3)`, [pending.plantId, pending.id, photo]);

  const roles = { alice: "Botanist", bob: "Botanist", officer: "Conservation Officer" };
  const tokens = Object.fromEntries(Object.keys(roles).map((name, index) => [name, String(index + 1).repeat(64)]));
  const auth = { session: async (token) => {
    const user = Object.keys(tokens).find((name) => tokens[name] === token);
    return user ? { id: user, role: roles[user], status: "Active", mustChangePassword: false } : null;
  }, event: async () => {} };
  const server = createPlantApp({ pool, auth, origins: new Set() }).listen(0, "127.0.0.1");
  await once(server, "listening");
  t.after(async () => { server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); });
  async function call(path, user, body = {}) {
    const response = await fetch(`http://127.0.0.1:${server.address().port}/api${path}`, {
      method: "POST", headers: { "Content-Type": "application/json", Authorization: `Bearer ${tokens[user]}` }, body: JSON.stringify(body),
    });
    return { status: response.status, data: await response.json() };
  }
  const withdraw = (row, user = "alice", body = {}) => call(`/observations/${row.id}/withdraw`, user, body);

  assert.equal((await withdraw(pending, "bob")).status, 403);
  assert.equal((await withdraw(pending, "officer")).status, 403);
  assert.equal((await withdraw(pending, "alice", { status: "Approved" })).status, 400);
  assert.equal((await withdraw(approved)).status, 409);
  assert.equal((await withdraw(rejected)).status, 409);
  assert.equal((await withdraw(initial)).status, 409);
  assert.equal((await withdraw(blockedParent)).status, 409);
  assert.equal((await withdraw(resubmitted)).status, 409);
  assert.equal((await withdraw(pending)).status, 409, "active edit blocks separate withdrawal");
  await pool.query("UPDATE observation_edit_request SET status='Rejected' WHERE id='active-edit'");

  const correctionResult = await withdraw(correction);
  assert.equal(correctionResult.status, 200, JSON.stringify(correctionResult.data));
  assert.equal(correctionResult.data.observation.status, "Withdrawn");
  assert.equal(correctionResult.data.observation.withdrawn_by, "staff:alice");
  assert.ok(correctionResult.data.observation.withdrawn_at);
  assert.equal((await withdraw(correction)).status, 409, "repeated withdrawal is rejected");
  const correctionAudit = (await pool.query(`SELECT comment,decision FROM observation_review WHERE id='correction-history'`)).rows[0];
  assert.deepEqual(correctionAudit, { comment: "Keep this feedback", decision: "Correction Required" });

  const withdrawn = await withdraw(pending);
  assert.equal(withdrawn.status, 200, JSON.stringify(withdrawn.data));
  const preserved = (await pool.query(`SELECT o.status,o.content,o.withdrawn_by,o.withdrawn_at,
    (SELECT count(*)::int FROM plant_asset WHERE observation_id=o.id) AS photos,
    (SELECT rbac_status FROM plant_record WHERE plant_id=o.plant_id) AS parent_status
    FROM plant_observation o WHERE o.id=$1`, [pending.id])).rows[0];
  assert.equal(preserved.status, "Withdrawn");
  assert.equal(preserved.content.notes, "Preserve me");
  assert.equal(preserved.withdrawn_by, "staff:alice");
  assert.ok(preserved.withdrawn_at);
  assert.equal(preserved.photos, 1);
  assert.equal(preserved.parent_status, "Approved");
  const officerQueue = await fetch(`http://127.0.0.1:${server.address().port}/api/observations?status=Pending%20Review`, {
    headers: { Authorization: `Bearer ${tokens.officer}` },
  });
  assert.equal(officerQueue.status, 200);
  const queueData = await officerQueue.json();
  assert.equal(queueData.observations.some((row) => row.id === pending.id || row.id === correction.id), false);
  const ownerHistory = await fetch(`http://127.0.0.1:${server.address().port}/api/observations/${pending.id}`, {
    headers: { Authorization: `Bearer ${tokens.alice}` },
  });
  const ownerHistoryData = await ownerHistory.json();
  assert.equal(ownerHistory.status, 200, JSON.stringify(ownerHistoryData));
  assert.equal(ownerHistoryData.observation.status, "Withdrawn");

  const concurrent = await observation("Pending Review");
  const race = await Promise.all([
    withdraw(concurrent),
    call(`/observations/${concurrent.id}/review`, "officer", { decision: "Approved", comment: "Reviewed", revision: 1 }),
  ]);
  assert.deepEqual(race.map((result) => result.status).sort(), [200, 409]);
  const final = (await pool.query("SELECT status FROM plant_observation WHERE id=$1", [concurrent.id])).rows[0].status;
  assert.ok(["Approved", "Withdrawn"].includes(final));

  // A Botanist other than the owner cannot discover or read the withdrawn row
  // through the scientific list unless it remains Approved and public.
  const other = await fetch(`http://127.0.0.1:${server.address().port}/api/observations/${pending.id}`, {
    headers: { Authorization: `Bearer ${tokens.bob}` },
  });
  assert.equal(other.status, 404);
});
