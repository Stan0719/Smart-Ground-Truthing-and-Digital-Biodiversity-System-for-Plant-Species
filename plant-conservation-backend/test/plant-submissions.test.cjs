"use strict";
const test = require("node:test"), assert = require("node:assert/strict");
const { readFileSync } = require("node:fs"), { join } = require("node:path"), { once } = require("node:events");
const sharp = require("sharp");
const { createPlantDatabase } = require("./postgres-fixture.cjs");
const { createPlantApp } = require("../server.js");
test("one atomic submission supports existing and pending species without partial or duplicate records", async (t) => {
  const database = await createPlantDatabase(); t.after(() => database.end());
  for (const file of ["004-species-requests.sql", "005-plant-scientific-name.sql", "006-atomic-plant-submissions.sql"])
    await database.query(readFileSync(join(__dirname, "../migrations", file), "utf8"));
  await database.query(readFileSync(join(__dirname, "../migrations/006-atomic-plant-submissions.sql"), "utf8"));
  await database.query("CREATE TABLE public.qr_code(qr_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,plant_id INTEGER,qr_code TEXT,status TEXT,generated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,assigned_at TIMESTAMPTZ,activated_at TIMESTAMPTZ,retired_at TIMESTAMPTZ)");
  await database.query("INSERT INTO species(scientific_name,common_name) VALUES('Existing species','Existing common name'); INSERT INTO rbac_species_visibility VALUES(1,'public'); INSERT INTO public.qr_code(qr_code,status) VALUES('qr-1','generated'),('qr-2','generated'),('qr-3','generated'),('qr-4','generated')");
  let failAsset = false;
  const pool = { query: (...args) => database.query(...args), connect: async () => {
    const c = await database.connect(); return { release: () => c.release(), query: async (sql, args) => {
      if (failAsset && sql.startsWith("INSERT INTO plant_asset")) { failAsset = false; throw Object.assign(Error("Injected upload storage failure"), { code: "XX000" }); }
      return c.query(sql, args);
    } };
  } };
  const roles = { bot: "Botanist", other: "Botanist", officer: "Conservation Officer", visitor: "Visitor" };
  const tokens = Object.fromEntries(Object.keys(roles).map((key, i) => [key, String(i + 1).repeat(64)]));
  const auth = { session: async (token) => { const key = Object.keys(tokens).find((key) => tokens[key] === token); return key ? { id: key, role: roles[key], status: "Active", mustChangePassword: false } : null; }, event: async () => {} };
  const server = createPlantApp({ pool, auth }).listen(0, "127.0.0.1"); await once(server, "listening");
  t.after(async () => { server.closeAllConnections(); await new Promise((r) => server.close(r)); });
  const base = `http://127.0.0.1:${server.address().port}/api`;
  async function call(path, role = "bot", method = "GET", body) {
    const r = await fetch(base + path, { method, headers: { "Content-Type": "application/json", ...(tokens[role] ? { Authorization: `Bearer ${tokens[role]}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: r.status, data: r.headers.get("content-type")?.includes("json") ? await r.json() : Buffer.from(await r.arrayBuffer()) };
  }
  const photo = { content_type: "image/png", base64: (await sharp({ create: { width: 4, height: 4, channels: 3, background: "green" } }).png().toBuffer()).toString("base64") };
  const species = { scientific_name: "New species name", common_name: "New common name", genus_name: "New genus", family_name: "New family", conservation_status: "Least Concern", description: "Species description", habitat: "Species habitat", photo };
  const plant = { scientific_name: "Independent individual plant name", latitude: 4.5, longitude: 113.7, qr_id: 1, client_key: "existing-1", photos: [photo, photo, photo], content: { heightCm: 80, healthStatus: "Healthy", lifeStage: "Juvenile", morphology: "Plant morphology", zone: "Zone A", altitudeM: 5 } };
  const count = async (table) => Number((await database.query(`SELECT count(*) AS count FROM ${table}`)).rows[0].count);
  await t.test("existing species creates only a linked plant; photos and QR assignment commit together", async () => {
    const before = await call("/qr-codes");
    assert.equal(before.status, 200);
    assert.equal(before.data.qr_codes.length, 4);
    assert.ok(before.data.qr_codes.every((code) => code.plant_id == null));
    assert.deepEqual((await call("/qr/qr-1", "guest")).data, { assigned: false });
    const r = await call("/plant-submissions", "bot", "POST", { ...plant, species_id: 1 });
    assert.equal(r.status, 201, JSON.stringify(r.data)); assert.equal(await count("species"), 1); assert.equal(await count("plant_record"), 1);
    assert.equal(r.data.qr_token, "qr-1"); assert.equal(r.data.species_request_id, null);
    const saved = (await database.query("SELECT * FROM plant_record WHERE plant_id=$1", [r.data.plant_id])).rows[0];
    assert.equal(Number(saved.species_id), 1); assert.equal(saved.scientific_name, plant.scientific_name);
    assert.equal((await database.query("SELECT scientific_name FROM species WHERE species_id=1")).rows[0].scientific_name, "Existing species");
    assert.equal(await count("plant_asset"), 3);
    const inventory = (await call("/qr-codes")).data.qr_codes;
    assert.equal(inventory.find((code) => Number(code.qr_id) === 1).plant_id, r.data.plant_id);
    assert.equal(inventory.find((code) => Number(code.qr_id) === 1).status, "assigned");
    assert.equal(inventory.find((code) => Number(code.qr_id) === 1).plant_name, plant.scientific_name);
  });
  const proposed = { ...plant, new_species: species, qr_id: 2, client_key: "new-1" };
  let combined;
  await t.test("new species and plant save atomically, with independent names and pending approvals", async () => {
    const r = await call("/plant-submissions", "bot", "POST", proposed); assert.equal(r.status, 201, JSON.stringify(r.data)); combined = r.data;
    assert.equal(await count("species"), 2); assert.equal(await count("plant_record"), 2);
    const s = (await database.query("SELECT * FROM species WHERE species_id=$1", [combined.species_id])).rows[0];
    const p = (await database.query("SELECT * FROM plant_record WHERE plant_id=$1", [combined.plant_id])).rows[0];
    assert.equal(s.scientific_name, species.scientific_name); assert.equal(s.common_name, species.common_name);
    assert.equal(s.rbac_data.habitat, species.habitat); assert.equal(s.rbac_data.approvalStatus, "Pending Review");
    assert.equal(p.scientific_name, plant.scientific_name); assert.equal(Number(p.species_id), Number(s.species_id)); assert.equal(p.rbac_status, "Pending Review");
    assert.equal((await call("/species?scope=scientific")).data.species.length, 1);
    assert.equal((await call(`/species/${combined.species_id}`)).status, 404);
    assert.equal((await call(`/qr/${combined.qr_token}`, "guest")).status, 404);
  });
  await t.test("submitter can read their pending plant, observation, request and photos; other users cannot", async () => {
    const own = await call(`/plants/${combined.plant_id}`);
    assert.equal(own.status, 200, JSON.stringify(own.data));
    assert.equal(own.data.plant.registered_subject, "staff:bot");
    assert.equal(own.data.plant.rbac_status, "Pending Review");
    assert.equal(own.data.plant.latest_submission.heightCm, 80);
    assert.equal(own.data.plant.latest_submission.lifeStage, "Juvenile");
    assert.equal(own.data.plant.latest_submission.healthStatus, "Healthy");
    assert.equal(own.data.plant.latest_submission.morphology, "Plant morphology");
    assert.equal(own.data.plant.latest_submission.latitude, undefined);
    assert.equal(own.data.plant.latest_submission.longitude, undefined);
    assert.equal(own.data.plant.species_details.scientific_name, species.scientific_name);
    assert.equal(own.data.plant.scientific_name, plant.scientific_name);
    assert.equal(own.data.plant.latitude, null); // Pending plant GPS is not projected as approved.
    assert.equal(own.data.plant.latest_submission.latitude, undefined);
    assert.ok((await call("/plants")).data.plants.some((p) => String(p.plant_id) === String(combined.plant_id)));
    const observation = await call(`/observations/${combined.id}`);
    assert.equal(observation.status, 200); assert.equal(observation.data.observation.owner_subject, "staff:bot");
    assert.equal(observation.data.observation.status, "Pending Review");
    assert.ok((await call("/species-requests")).data.species_requests.some((r) => r.request_id === combined.species_request_id));
    for (const role of ["other", "guest", "visitor"]) {
      assert.equal((await call(`/plants/${combined.plant_id}`, role)).status, 404);
      assert.ok(!(await call("/plants", role)).data.plants.some((p) => String(p.plant_id) === String(combined.plant_id)));
    }
    assert.equal((await call(`/observations/${combined.id}`, "other")).status, 404);
    assert.equal((await call(`/species-requests/${combined.species_request_id}`, "other")).status, 404);
    const asset = (await database.query("SELECT id FROM plant_asset WHERE plant_id=$1 LIMIT 1", [combined.plant_id])).rows[0];
    assert.equal((await call(`/assets/${asset.id}`)).status, 200);
    assert.equal((await call(`/assets/${asset.id}`, "other")).status, 404);
    assert.equal((await call(`/assets/${asset.id}`, "guest")).status, 404);
    assert.equal((await call(`/plants/${combined.plant_id}`, "officer")).status, 200);
    assert.equal(await count("species"), 2); assert.equal(await count("plant_record"), 2);
  });
  await t.test("identical retries/concurrent taps return the same record; altered retries and duplicate species fail", async () => {
    const results = await Promise.all([call("/plant-submissions", "bot", "POST", proposed), call("/plant-submissions", "bot", "POST", proposed)]);
    for (const r of results) { assert.equal(r.status, 201); assert.equal(r.data.plant_id, combined.plant_id); }
    assert.equal(await count("plant_record"), 2); assert.equal(await count("species"), 2);
    assert.equal((await call("/plant-submissions", "bot", "POST", { ...proposed, scientific_name: "Changed" })).status, 409);
    assert.equal((await call("/plant-submissions", "other", "POST", { ...proposed, qr_id: 3, client_key: "duplicate" })).status, 409);
  });
  await t.test("storage failure rolls back species, plant, taxonomy, photos, request, receipt and QR assignment", async () => {
    const tables = ["species", "plant_record", "genus", "family", "plant_location", "plant_observation", "plant_asset", "species_request_submission", "plant_submission_receipt"];
    const before = await Promise.all(tables.map(count));
    const body = { ...proposed, qr_id: 3, client_key: "rollback", new_species: { ...species, scientific_name: "Rollback species", genus_name: "Rollback genus", family_name: "Rollback family" } };
    failAsset = true; const r = await call("/plant-submissions", "bot", "POST", body); assert.equal(r.status, 503);
    assert.deepEqual(await Promise.all(tables.map(count)), before);
    assert.equal((await database.query("SELECT status FROM public.qr_code WHERE qr_id=3")).rows[0].status, "generated");
    const retry = await call("/plant-submissions", "bot", "POST", body); assert.equal(retry.status, 201, JSON.stringify(retry.data));
    assert.equal(await count("plant_record"), 3);
  });
  await t.test("required fields, invalid images and unavailable QR fail without writes", async () => {
    const before = await count("species");
    for (const key of ["scientific_name", "common_name", "genus_name", "family_name", "conservation_status", "description", "habitat", "photo"]) {
      const data = { ...species }; delete data[key];
      assert.equal((await call("/plant-submissions", "bot", "POST", { ...proposed, client_key: "invalid", new_species: data })).status, 400, key);
    }
    assert.equal((await call("/plant-submissions", "bot", "POST", { ...plant, species_id: 1, scientific_name: " " })).status, 400);
    assert.equal((await call("/plant-submissions", "bot", "POST", { ...plant, species_id: 1, photos: [] })).status, 400);
    assert.equal((await call("/plant-submissions", "bot", "POST", { ...proposed, client_key: "qr-conflict", qr_id: 1, new_species: { ...species, scientific_name: "QR conflict species" } })).status, 409);
    assert.equal(await count("species"), before);
  });
  await t.test("authorization and officer approval are preserved; approval reuses the pending species", async () => {
    assert.equal((await call("/plant-submissions", "visitor", "POST", proposed)).status, 403);
    assert.equal((await call(`/species-requests/${combined.species_request_id}/review`, "bot", "POST", { decision: "Approved", comment: "Try", visibility: "internal" })).status, 403);
    const reviewBody = { decision: "Approved", comment: "Checked", revision: 1 };
    assert.equal((await call(`/observations/${combined.id}/review`, "officer", "POST", reviewBody)).status, 409);
    const before = await count("species");
    const approved = await call(`/species-requests/${combined.species_request_id}/review`, "officer", "POST", { decision: "Approved", comment: "Taxonomy verified", visibility: "internal" });
    assert.equal(approved.status, 200, JSON.stringify(approved.data)); assert.equal(Number(approved.data.species_request.approved_species_id), Number(combined.species_id));
    assert.equal(await count("species"), before);
    assert.equal((await call(`/species/${combined.species_id}`)).status, 200);
    const approvedSpecies = (await database.query("SELECT rbac_data FROM species WHERE species_id=$1", [combined.species_id])).rows[0];
    assert.equal(approvedSpecies.rbac_data.approvalStatus, "Approved");
    assert.equal(approvedSpecies.rbac_data.submittedBy, "staff:bot");
    assert.equal((await call(`/species-requests/${combined.species_request_id}`)).data.species_request.request_status, "Approved");
    assert.equal((await call(`/observations/${combined.id}/review`, "officer", "POST", reviewBody)).status, 200);
    const own = await call(`/plants/${combined.plant_id}?scope=mine`);
    assert.equal(own.status, 200);
    assert.equal(own.data.plant.rbac_status, "Approved");
    assert.equal(own.data.plant.registered_subject, "staff:bot");
    assert.equal(own.data.plant.scientific_name, plant.scientific_name);
    const resolved = await call(`/qr/${combined.qr_token}`, "bot");
    assert.equal(resolved.status, 200, JSON.stringify(resolved.data));
    assert.equal(resolved.data.assigned, true);
    assert.equal(String(resolved.data.plant.plant_id), String(combined.plant_id));
    const photos = await call(`/assets?plant_id=${combined.plant_id}`, "bot");
    assert.equal(photos.status, 200);
    assert.equal(photos.data.assets.length, 3);
    assert.equal((await call(`/assets?plant_id=${combined.plant_id}`, "guest")).data.assets.length, 0);
    assert.ok((await call("/plants?scope=mine")).data.plants.some((p) => String(p.plant_id) === String(combined.plant_id)));
    assert.ok((await call("/species?scope=scientific")).data.species.some((s) => String(s.species_id) === String(combined.species_id)));
    assert.equal((await call(`/plants/${combined.plant_id}?scope=mine`, "other")).status, 404);
    assert.equal((await call("/plants?scope=mine", "guest")).status, 401);
    assert.equal((await call("/plants?scope=mine", "visitor")).status, 403);
  });
  await t.test("existing-species registration by another Botanist and later visits do not inherit the originating species request", async () => {
    const beforeRequests = await count("species_request_submission");
    const created = await call("/plant-submissions", "other", "POST", { ...plant, qr_id: 4, client_key: "reuse-approved-species", species_id: Number(combined.species_id) });
    assert.equal(created.status, 201, JSON.stringify(created.data));
    assert.equal(created.data.species_request_id, null);
    assert.equal(await count("species_request_submission"), beforeRequests);
    const detail = await call(`/observations/${created.data.id}`, "officer");
    assert.equal(detail.data.observation.species_request, null);
    assert.equal(detail.data.observation.species_request_id, null);
    assert.equal((await call(`/observations/${created.data.id}/review`, "officer", "POST", { decision: "Approved", comment: "Existing species", revision: 1 })).status, 200);
    const visit = await call(`/plants/${created.data.plant_id}/observations`, "other", "POST", { content: plant.content, client_key: "later-existing-species-visit" });
    assert.equal(visit.status, 201);
    assert.equal((await call(`/observations/${visit.data.id}/submit`, "other", "POST", {})).status, 200);
    const later = await call(`/observations/${visit.data.id}`, "officer");
    assert.equal(later.data.observation.species_request, null);
    assert.equal((await call(`/observations/${visit.data.id}/review`, "officer", "POST", { decision: "Approved", comment: "New visit", revision: 1 })).status, 200);
    const original = await call(`/observations/${combined.id}`, "officer");
    assert.equal(original.data.observation.species_request_id, String(combined.species_request_id));
  });

  await t.test("own history survives protected classification at every plant status without exposing the protected catalogue", async () => {
    await database.query("UPDATE rbac_species_visibility SET visibility='protected' WHERE species_id=$1", [combined.species_id]);
    const asset = (await database.query("SELECT id FROM plant_asset WHERE plant_id=$1 LIMIT 1", [combined.plant_id])).rows[0];
    for (const status of ["Pending Review", "Approved", "Rejected"]) {
      await database.query("UPDATE plant_record SET rbac_status=$1 WHERE plant_id=$2", [status, combined.plant_id]);
      const own = await call(`/plants/${combined.plant_id}?scope=mine`);
      assert.equal(own.status, 200, status);
      assert.equal(own.data.plant.rbac_status, status);
      assert.equal(own.data.plant.species_details, null);
      assert.equal(own.data.plant.common_name, null);
      assert.equal(own.data.plant.latitude, 4.5); // Owner scope exposes only the existing approved location.
      assert.equal(own.data.plant.latest_approved.latitude, undefined);
      assert.equal(own.data.plant.gps_access_restricted, undefined);
      assert.equal(own.data.plant.registered_subject, "staff:bot");
      assert.equal((await call(`/plants/${combined.plant_id}?scope=mine`, "other")).status, 404);
      assert.equal((await call(`/species/${combined.species_id}`)).status, 404);
      assert.ok(!(await call("/species?scope=scientific")).data.species.some((s) => String(s.species_id) === String(combined.species_id)));
      assert.equal((await call(`/observations/${combined.id}?scope=mine`)).status, 200);
      assert.equal((await call(`/observations/${combined.id}?scope=mine`, "other")).status, 404);
      assert.equal((await call(`/assets/${asset.id}?scope=mine`)).status, status === "Approved" ? 404 : 200, `plant status ${status}`);
      assert.equal((await call(`/assets/${asset.id}?scope=mine`, "other")).status, 404);
    }
    assert.equal((await call(`/qr/${combined.qr_token}`, "guest")).status, 404);
    assert.equal((await call(`/plants/${combined.plant_id}/qr`)).status, 404);
  });
});
