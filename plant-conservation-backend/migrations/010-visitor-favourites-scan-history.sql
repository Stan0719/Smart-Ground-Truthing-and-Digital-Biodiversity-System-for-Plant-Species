-- Additive Visitor personalization tables for the verified live schema.
-- This migration does not change or backfill existing account/plant data.
BEGIN;

DO $$
DECLARE
  existing_name TEXT;
BEGIN
  IF to_regclass('plant_app.plant_record') IS NULL OR to_regclass('plant_app.species') IS NULL
     OR to_regclass('public.qr_code') IS NULL THEN
    RAISE EXCEPTION 'Expected plant, species, and public QR tables are required; no changes made';
  END IF;

  SELECT table_name INTO existing_name
  FROM information_schema.tables
  WHERE table_schema = 'plant_app'
    AND table_type = 'BASE TABLE'
    AND table_name IN (
      'visitor_favourite', 'visitor_favourites', 'visitor_favorite', 'visitor_favorites',
      'visitor_scan_history', 'visitor_qr_scan_history'
    )
  LIMIT 1;
  IF existing_name IS NOT NULL THEN
    RAISE EXCEPTION 'Potential existing Visitor feature table % needs mapping/reuse review; no changes made', existing_name;
  END IF;
END;
$$;

CREATE TABLE plant_app.visitor_favourite (
  visitor_subject TEXT NOT NULL CHECK (visitor_subject LIKE 'visitor:%'),
  plant_id BIGINT REFERENCES plant_app.plant_record(plant_id) ON DELETE CASCADE,
  species_id BIGINT REFERENCES plant_app.species(species_id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (num_nonnulls(plant_id, species_id) = 1)
);

CREATE UNIQUE INDEX visitor_favourite_plant_unique
  ON plant_app.visitor_favourite(visitor_subject, plant_id) WHERE plant_id IS NOT NULL;
CREATE UNIQUE INDEX visitor_favourite_species_unique
  ON plant_app.visitor_favourite(visitor_subject, species_id) WHERE species_id IS NOT NULL;
CREATE INDEX visitor_favourite_subject_time
  ON plant_app.visitor_favourite(visitor_subject, created_at DESC);

CREATE TABLE plant_app.visitor_scan_history (
  scan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  visitor_subject TEXT NOT NULL CHECK (visitor_subject LIKE 'visitor:%'),
  plant_id BIGINT REFERENCES plant_app.plant_record(plant_id) ON DELETE SET NULL,
  plant_reference BIGINT NOT NULL,
  qr_id BIGINT REFERENCES public.qr_code(qr_id) ON DELETE SET NULL,
  qr_identifier TEXT NOT NULL,
  scanned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX visitor_scan_history_subject_time
  ON plant_app.visitor_scan_history(visitor_subject, scanned_at DESC, scan_id DESC);
CREATE INDEX visitor_scan_history_plant
  ON plant_app.visitor_scan_history(plant_id) WHERE plant_id IS NOT NULL;

-- The application authenticates through its own API and enforces visitor_subject.
-- Do not expose these owner-scoped records directly through Supabase REST.
ALTER TABLE plant_app.visitor_favourite ENABLE ROW LEVEL SECURITY;
ALTER TABLE plant_app.visitor_scan_history ENABLE ROW LEVEL SECURITY;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON plant_app.visitor_favourite, plant_app.visitor_scan_history FROM anon;
    REVOKE ALL ON SEQUENCE plant_app.visitor_scan_history_scan_id_seq FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON plant_app.visitor_favourite, plant_app.visitor_scan_history FROM authenticated;
    REVOKE ALL ON SEQUENCE plant_app.visitor_scan_history_scan_id_seq FROM authenticated;
  END IF;
  REVOKE ALL ON plant_app.visitor_favourite, plant_app.visitor_scan_history FROM PUBLIC;
  REVOKE ALL ON SEQUENCE plant_app.visitor_scan_history_scan_id_seq FROM PUBLIC;

END;
$$;

-- The live Plant API connection reports current_user=postgres and bypasses RLS.
GRANT SELECT, INSERT, DELETE ON plant_app.visitor_favourite TO postgres;
GRANT SELECT, INSERT ON plant_app.visitor_scan_history TO postgres;
GRANT USAGE, SELECT ON SEQUENCE plant_app.visitor_scan_history_scan_id_seq TO postgres;

COMMIT;
