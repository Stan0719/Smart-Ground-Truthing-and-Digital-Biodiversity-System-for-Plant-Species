-- Run separately in the configured PLANT_PG_SCHEMA (for example plant_app).
-- Set search_path to that schema before running. No legacy tables are altered.
BEGIN;
CREATE TABLE IF NOT EXISTS species_request_submission (
  request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_subject TEXT NOT NULL,
  client_key TEXT NOT NULL,
  payload_hash TEXT NOT NULL,
  scientific_name TEXT NOT NULL,
  common_name TEXT NOT NULL,
  genus_name TEXT NOT NULL,
  family_name TEXT NOT NULL,
  conservation_status TEXT NOT NULL,
  description TEXT NOT NULL,
  habitat TEXT NOT NULL,
  photo BYTEA NOT NULL CHECK(octet_length(photo) BETWEEN 1 AND 4194304),
  request_status TEXT NOT NULL DEFAULT 'Pending Review'
    CHECK(request_status IN ('Pending Review','Approved','Rejected','Correction Required')),
  review_comment TEXT,
  reviewed_by TEXT,
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  reviewed_at TIMESTAMPTZ,
  approved_species_id INTEGER REFERENCES species(species_id),
  UNIQUE(owner_subject,client_key),
  CHECK((request_status = 'Approved') = (approved_species_id IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS species_request_pending_name_idx
  ON species_request_submission(lower(btrim(scientific_name)))
  WHERE request_status = 'Pending Review';
-- Requests and photos are served by the authorized backend, not public PostgREST.
ALTER TABLE species_request_submission ENABLE ROW LEVEL SECURITY;
COMMIT;
