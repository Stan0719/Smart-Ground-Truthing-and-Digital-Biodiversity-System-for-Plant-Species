BEGIN;

DO $$
DECLARE
  legacy_table OID := to_regclass('public.qr_code');
  app_table OID := to_regclass('plant_app.qr_code');
  target_table OID;
  table_kind "char";
  qr_id_attnum SMALLINT;
  plant_id_attnum SMALLINT;
  qr_code_attnum SMALLINT;
  status_attnum SMALLINT;
  generated_at_attnum SMALLINT;
  parent_table OID;
  parent_plant_attnum SMALLINT;
  foreign_key_name TEXT;
  foreign_key_count INTEGER;
  mappings_to_review BOOLEAN;
BEGIN
  IF legacy_table IS NOT NULL AND app_table IS NOT NULL THEN
    RAISE EXCEPTION 'Both public.qr_code and plant_app.qr_code exist; manual review required';
  END IF;

  IF to_regclass('plant_app.plant_record') IS NULL THEN
    RAISE EXCEPTION 'plant_app.plant_record is required before moving the QR inventory';
  END IF;

  IF legacy_table IS NOT NULL THEN
    SELECT relkind INTO table_kind FROM pg_class WHERE oid = legacy_table;
    IF table_kind <> 'r' THEN
      RAISE EXCEPTION 'public.qr_code is not a regular table; manual review required';
    END IF;
    ALTER TABLE public.qr_code SET SCHEMA plant_app;
    target_table := to_regclass('plant_app.qr_code');
  ELSIF app_table IS NOT NULL THEN
    SELECT relkind INTO table_kind FROM pg_class WHERE oid = app_table;
    IF table_kind <> 'r' THEN
      RAISE EXCEPTION 'plant_app.qr_code is not a regular table; manual review required';
    END IF;
    target_table := app_table;
  ELSE
    CREATE TABLE plant_app.qr_code (
      qr_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      plant_id INTEGER UNIQUE REFERENCES plant_app.plant_record(plant_id) ON DELETE SET NULL,
      qr_code TEXT NOT NULL UNIQUE,
      status TEXT NOT NULL DEFAULT 'generated',
      generated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      assigned_at TIMESTAMPTZ,
      activated_at TIMESTAMPTZ,
      retired_at TIMESTAMPTZ
    );
    RETURN;
  END IF;

  SELECT attnum INTO qr_id_attnum
  FROM pg_attribute
  WHERE attrelid = target_table AND attname = 'qr_id' AND NOT attisdropped;
  SELECT attnum INTO plant_id_attnum
  FROM pg_attribute
  WHERE attrelid = target_table AND attname = 'plant_id' AND NOT attisdropped;
  SELECT attnum INTO qr_code_attnum
  FROM pg_attribute
  WHERE attrelid = target_table AND attname = 'qr_code' AND NOT attisdropped;
  SELECT attnum INTO status_attnum
  FROM pg_attribute
  WHERE attrelid = target_table AND attname = 'status' AND NOT attisdropped;
  SELECT attnum INTO generated_at_attnum
  FROM pg_attribute
  WHERE attrelid = target_table AND attname = 'generated_at' AND NOT attisdropped;

  IF qr_id_attnum IS NULL OR plant_id_attnum IS NULL OR qr_code_attnum IS NULL
     OR status_attnum IS NULL OR generated_at_attnum IS NULL
     OR NOT EXISTS (
       SELECT 1 FROM pg_attribute
       WHERE attrelid = target_table AND attname = 'assigned_at' AND NOT attisdropped
     )
     OR NOT EXISTS (
       SELECT 1 FROM pg_attribute
       WHERE attrelid = target_table AND attname = 'activated_at' AND NOT attisdropped
     )
     OR NOT EXISTS (
       SELECT 1 FROM pg_attribute
       WHERE attrelid = target_table AND attname = 'retired_at' AND NOT attisdropped
     ) THEN
    RAISE EXCEPTION 'QR inventory columns do not match the expected design; manual review required';
  END IF;

  IF (
    SELECT count(*)
    FROM pg_attribute
    WHERE attrelid = target_table AND attnum > 0 AND NOT attisdropped
  ) <> 8 THEN
    RAISE EXCEPTION 'QR inventory has unexpected columns; manual review required';
  END IF;

  IF (
    SELECT count(*)
    FROM pg_constraint
    WHERE conrelid = target_table AND contype = 'p'
  ) <> 1 OR (
    SELECT count(*)
    FROM pg_constraint
    WHERE conrelid = target_table AND contype = 'u'
  ) <> 2 OR (
    SELECT count(*)
    FROM pg_constraint
    WHERE conrelid = target_table AND contype = 'f'
  ) <> 1 OR EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = target_table AND contype NOT IN ('p', 'u', 'f', 'n')
  ) THEN
    RAISE EXCEPTION 'QR inventory has unexpected constraints; manual review required';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM (VALUES
      ('qr_id', 'bigint'::regtype),
      ('plant_id', 'integer'::regtype),
      ('qr_code', 'text'::regtype),
      ('status', 'text'::regtype),
      ('generated_at', 'timestamptz'::regtype),
      ('assigned_at', 'timestamptz'::regtype),
      ('activated_at', 'timestamptz'::regtype),
      ('retired_at', 'timestamptz'::regtype)
    ) AS expected(column_name, expected_type)
    LEFT JOIN pg_attribute actual
      ON actual.attrelid = target_table
     AND actual.attname = expected.column_name
     AND NOT actual.attisdropped
    WHERE actual.attnum IS NULL OR actual.atttypid <> expected.expected_type
  ) THEN
    RAISE EXCEPTION 'QR inventory column data types do not match the expected design; manual review required';
  END IF;

  IF NOT EXISTS (
       SELECT 1 FROM pg_attribute
       WHERE attrelid = target_table AND attnum = qr_id_attnum AND attidentity = 'd'
     )
     OR NOT EXISTS (
       SELECT 1 FROM pg_constraint
       WHERE conrelid = target_table AND contype = 'p'
         AND conkey = ARRAY[qr_id_attnum]::SMALLINT[]
     )
     OR NOT EXISTS (
       SELECT 1 FROM pg_attribute
       WHERE attrelid = target_table AND attnum = qr_code_attnum AND attnotnull
     )
     OR EXISTS (
       SELECT 1 FROM pg_attribute
       WHERE attrelid = target_table AND attnum = plant_id_attnum AND attnotnull
     )
     OR EXISTS (
       SELECT 1 FROM pg_attribute
       WHERE attrelid = target_table
         AND attname IN ('assigned_at', 'activated_at', 'retired_at')
         AND attnotnull
     )
     OR NOT EXISTS (
       SELECT 1 FROM pg_attribute
       WHERE attrelid = target_table AND attnum = status_attnum AND attnotnull
     )
     OR NOT EXISTS (
       SELECT 1 FROM pg_attribute
       WHERE attrelid = target_table AND attnum = generated_at_attnum AND attnotnull
     )
     OR NOT EXISTS (
       SELECT 1 FROM pg_index
       WHERE indrelid = target_table AND indisunique AND indisvalid
         AND indpred IS NULL AND indnkeyatts = 1 AND indkey[0] = plant_id_attnum
     )
     OR NOT EXISTS (
       SELECT 1 FROM pg_index
       WHERE indrelid = target_table AND indisunique AND indisvalid
         AND indpred IS NULL AND indnkeyatts = 1 AND indkey[0] = qr_code_attnum
     )
     OR NOT EXISTS (
       SELECT 1 FROM pg_attrdef
       WHERE adrelid = target_table AND adnum = status_attnum
         AND lower(pg_get_expr(adbin, adrelid)) = '''generated''::text'
     )
     OR NOT EXISTS (
       SELECT 1 FROM pg_attrdef
       WHERE adrelid = target_table AND adnum = generated_at_attnum
         AND lower(pg_get_expr(adbin, adrelid)) = 'current_timestamp'
     )
     OR EXISTS (
       SELECT 1
       FROM pg_attrdef default_row
       JOIN pg_attribute column_row
         ON column_row.attrelid = default_row.adrelid
        AND column_row.attnum = default_row.adnum
       WHERE default_row.adrelid = target_table
         AND column_row.attname IN (
           'plant_id', 'qr_code', 'assigned_at', 'activated_at', 'retired_at'
         )
     ) THEN
    RAISE EXCEPTION 'QR inventory constraints or defaults do not match the expected design; manual review required';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_class identity_sequence
    JOIN pg_namespace identity_schema
      ON identity_schema.oid = identity_sequence.relnamespace
    WHERE identity_sequence.oid =
        to_regclass(pg_get_serial_sequence('plant_app.qr_code', 'qr_id'))
      AND identity_sequence.relkind = 'S'
      AND identity_schema.nspname = 'plant_app'
  ) THEN
    RAISE EXCEPTION 'QR inventory identity sequence is not associated with qr_id in plant_app; manual review required';
  END IF;

  SELECT count(*), (array_agg(c.conname))[1], (array_agg(c.confrelid))[1]
    INTO foreign_key_count, foreign_key_name, parent_table
  FROM pg_constraint c
  WHERE c.conrelid = target_table AND c.contype = 'f'
    AND c.conkey @> ARRAY[plant_id_attnum]::SMALLINT[];

  IF foreign_key_count <> 1 THEN
    RAISE EXCEPTION 'Expected exactly one QR-to-plant foreign key; manual review required';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint c
    JOIN pg_attribute parent_column
      ON parent_column.attrelid = c.confrelid
     AND parent_column.attname = 'plant_id'
     AND NOT parent_column.attisdropped
    WHERE c.conrelid = target_table
      AND c.conname = foreign_key_name
      AND c.contype = 'f'
      AND c.conkey = ARRAY[plant_id_attnum]::SMALLINT[]
      AND c.confkey = ARRAY[parent_column.attnum]::SMALLINT[]
      AND c.confdeltype = 'n'
      AND c.confupdtype = 'a'
      AND c.confmatchtype = 's'
      AND NOT c.condeferrable
      AND c.convalidated
  ) THEN
    RAISE EXCEPTION 'QR-to-plant foreign key has an unexpected definition; manual review required';
  END IF;

  IF parent_table <> to_regclass('plant_app.plant_record')
     AND parent_table <> to_regclass('public.plant_record') THEN
    RAISE EXCEPTION 'QR inventory references an unexpected plant table; manual review required';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM plant_app.qr_code q
    LEFT JOIN plant_app.plant_record p ON p.plant_id = q.plant_id
    WHERE q.plant_id IS NOT NULL
      AND (p.plant_id IS NULL OR p.qr_token IS DISTINCT FROM q.qr_code)
  ) THEN
    RAISE EXCEPTION 'Existing assigned QR mappings need manual review; no changes made';
  END IF;

  IF parent_table = to_regclass('public.plant_record') THEN
    SELECT EXISTS (
      SELECT 1
      FROM plant_app.qr_code q
      LEFT JOIN plant_app.plant_record app_plant ON app_plant.plant_id = q.plant_id
      LEFT JOIN public.plant_record legacy_plant ON legacy_plant.plant_id = q.plant_id
      WHERE q.plant_id IS NOT NULL
        AND (app_plant.plant_id IS NULL OR legacy_plant.plant_id IS NULL
          OR app_plant.species_id IS DISTINCT FROM legacy_plant.species_id)
    ) INTO mappings_to_review;

    IF mappings_to_review THEN
      RAISE EXCEPTION 'Existing assigned QR mappings need manual review; no changes made';
    END IF;

    SELECT attnum INTO parent_plant_attnum
    FROM pg_attribute
    WHERE attrelid = to_regclass('plant_app.plant_record')
      AND attname = 'plant_id' AND NOT attisdropped;
    IF parent_plant_attnum IS NULL THEN
      RAISE EXCEPTION 'plant_app.plant_record has no plant_id column; manual review required';
    END IF;

    EXECUTE format('ALTER TABLE plant_app.qr_code DROP CONSTRAINT %I', foreign_key_name);
    EXECUTE format(
      'ALTER TABLE plant_app.qr_code ADD CONSTRAINT %I FOREIGN KEY (plant_id) REFERENCES plant_app.plant_record(plant_id) ON DELETE SET NULL',
      foreign_key_name
    );
  END IF;
END;
$$;

COMMIT;
